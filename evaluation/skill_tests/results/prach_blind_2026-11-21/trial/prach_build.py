"""prach_build.py -- the PRACH searcher's build DAG.

    python prach_build.py --through codegen             # headers, the five tops and their .tcl
    python prach_build.py --through pysim               # the composite in pysim
    python prach_build.py --through front_compare       # front alone, at RTL   (needs Vitis + Vivado)
    python prach_build.py                               # the composite through compare (needs both)

The four stages' bodies are hand-written (``src/``); everything else is generated: the schemas' C++
(with framed readers and writers for the internal FIFOs), the lane routines of every complex format,
both FFTs' configurations, task wrappers and bodies (``waveflow.dsp.ssr_fft.hls.write_sources``), and
five free-running tops -- the composite, and each stage alone, so each is verified in its own harness
before the composite.  One body serves a stage in both places (``KernelTask.framed``).

The part and clock are the RFSoC 4x2's xczu48dr at 250 MHz (``RFSOC4X2_PART``, 4 ns): the FFTs are
measured there.
"""
from __future__ import annotations

import shutil
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, ClassVar

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from waveflow.build.build import BuildConfig, BuildDag, BuildStep  # noqa: E402
from waveflow.build.composite_gen import (GEN_DIR, INCLUDE_DIR, RFSOC4X2_PART,  # noqa: E402
                                          RFSOC4X2_PERIOD_NS, composite_top_spec, render_tcl,
                                          render_top, tcl_path)
from waveflow.build.streamutils import MemMgrStep, StreamUtilsStep  # noqa: E402
from waveflow.build.system_dag import add_system_steps  # noqa: E402
from waveflow.dsp.ssr_fft import hls as fft_hls  # noqa: E402
from waveflow.hw.arrayutils import ArrayUtilsStep  # noqa: E402
from waveflow.hw.dataschema import DataSchemaStep  # noqa: E402
from waveflow.hw.harness import harness  # noqa: E402
from waveflow.simulation.simulation import Simulation  # noqa: E402

from prach.prach import (C16, SCHEMA_CLASSES, U8, W, Correlate, Detect, Extract,  # noqa: E402
                         Front, PrachSearcher)

WORK_DIR = "xsi_work"
SRC = HERE / "src"
TOP = "prach_searcher_top"
STAGE_TOPS = {Front: "prach_front_top", Extract: "prach_extract_top",
              Correlate: "prach_correlate_top", Detect: "prach_detect_top"}
SOLUTION_CONFIG = ("config_rtl -reset state",)     # the FFTs' one setting (dsp/ssr_fft/build.md)


def gen_headers(root: Path = HERE) -> None:
    dag = BuildDag()
    dag.add(StreamUtilsStep(output_dir=INCLUDE_DIR))
    dag.add(MemMgrStep(output_dir=INCLUDE_DIR))
    for cls in SCHEMA_CLASSES:
        dag.add(DataSchemaStep(cls, word_bw_supported=[W], include_dir=INCLUDE_DIR, framed=True))
    dag.add(ArrayUtilsStep(U8, [W]))
    res = dag.run(BuildConfig(root_dir=root, params={}), force=True)
    bad = [k for k, r in res.items() if not r.success]
    if bad:
        raise RuntimeError(f"header generation failed: {bad}")
    # Both FFTs' configuration headers, task wrappers, bodies and every edge's lane routines --
    # C16 (<16,2>, the input and our framed samples), C27 (<27,13>) and C25 (<25,11>) among them.
    mod = PrachSearcher(name="prach_searcher", sim=Simulation())
    for fft in (mod.fft1, mod.fft2):
        fft_hls.write_sources(fft.geo, root, INCLUDE_DIR, reorder=fft.reorder)
    # C16 at the framed word too (the FFT writes it at 128 and 32 already; regenerate all three).
    ArrayUtilsStep(C16, [32, W]).run(BuildConfig(root_dir=root / INCLUDE_DIR))
    (root / INCLUDE_DIR / "prach_rom.h").write_text(render_rom(), encoding="utf-8")
    for h in SRC.glob("*.h"):
        shutil.copy(h, root / INCLUDE_DIR / h.name)


def render_rom() -> str:
    """``prach_rom.h``: correlate's reference ROM, ``exp(j pi p / 139)`` as ``ap_fixed<16, 1>``, from
    :func:`prach.golden.phase_rom` -- one copy per lane, so four lanes read it in one cycle."""
    from prach.golden import N_PHASE, phase_rom
    c, s = phase_rom()

    def table(name, vals):
        # four separate arrays, one per lane: each is its own ROM with one read a cycle, so no
        # ARRAY_PARTITION of a namespace-scope array is needed (decision 19's review)
        row = ", ".join(repr(float(v) / 2 ** 15) for v in vals)
        arrays = [f"static const r_t {name}{m}[{N_PHASE}] = {{{row}}};" for m in range(4)]
        sel = "\n".join([f"inline r_t {name}_at(int lane, ap_uint<9> p) {{",
                         "    switch (lane) {",
                         *[f"    case {m}: return {name}{m}[p];" for m in range(3)],
                         f"    default: return {name}3[p];",
                         "    }",
                         "}"])
        return "\n".join(arrays + [sel])

    return "\n".join([
        "// prach_rom.h -- GENERATED by prach_build.py::render_rom from prach.golden.phase_rom.",
        "// DO NOT EDIT: regenerate instead.",
        "#ifndef PRACH_ROM_H",
        "#define PRACH_ROM_H",
        "#include <ap_int.h>",
        "#include <ap_fixed.h>",
        "namespace prach_rom {",
        "typedef ap_fixed<16, 1> r_t;     // rnd(2^15 cos), saturated to [-1, 1 - 2^-15]",
        "// cos_at(lane, p) / sin_at(lane, p): lane a compile-time constant in an unrolled loop",
        table("cos", c),
        table("sin", s),
        "}  // namespace prach_rom",
        "#endif  // PRACH_ROM_H",
        "",
    ])


def gen_top(mod, root: Path = HERE) -> str:
    """The module's own free-running top, ``gen/<cpp_kernel_name>.cpp``, and its csynth script.
    (``add_system_steps`` names the harness system's work directory by its own ``top``.)"""
    widths = {name: int(ep.bitwidth) for name, ep in mod.boundary}
    spec = composite_top_spec(mod, width=W, port_widths=widths)
    gen = root / GEN_DIR
    gen.mkdir(parents=True, exist_ok=True)
    (gen / f"{spec.top_name}.cpp").write_text(render_top(spec), encoding="utf-8")
    tcl_path(root, spec.top_name).write_text(
        render_tcl(spec.top_name, part=RFSOC4X2_PART, period_ns=RFSOC4X2_PERIOD_NS,
                   solution_config=SOLUTION_CONFIG), encoding="utf-8")
    return spec.top_name


def generate(root: Path = HERE) -> list[str]:
    """Everything before csynth: the headers, and the five tops with their ``.tcl``."""
    gen_headers(root)
    tops = [gen_top(PrachSearcher(name="prach_searcher", sim=Simulation()), root)]
    for cls in STAGE_TOPS:
        tops.append(gen_top(cls(name=cls.cpp_kernel_name, sim=Simulation()), root))
    return tops


@dataclass(kw_only=True)
class PrachCodegenStep(BuildStep):
    """``codegen``: :func:`generate`.  Never fresh; csynth decides by content."""

    description = "Generate the headers, both FFTs' sources, the lane routines and the five tops."
    params: ClassVar[dict] = {}
    produces: ClassVar[dict] = {"include": Path(INCLUDE_DIR), "gen": Path(GEN_DIR)}

    def is_fresh(self, config: BuildConfig, paths: dict[str, Path]) -> bool:
        return False

    def run(self, config: BuildConfig, **_: Any) -> dict[str, Any]:
        root = Path(config.root_dir)
        generate(root)
        return {"include": root / INCLUDE_DIR, "gen": root / GEN_DIR}


def build_dag(work_dir=WORK_DIR) -> BuildDag:
    """``codegen``; the composite's harness on each scenario; each stage's harness."""
    dag = BuildDag()
    dag.add(PrachCodegenStep(name="codegen"))
    add_system_steps(dag, harness(PrachSearcher, workload="test"), work_dir=work_dir, top=TOP)
    add_system_steps(dag, harness(PrachSearcher, workload="early"), work_dir=work_dir, top=TOP,
                     prefix="early_")
    for kind in ("badroot", "late", "lateroots", "latecmd"):
        add_system_steps(dag, harness(PrachSearcher, workload=kind), work_dir=work_dir, top=TOP,
                         prefix=f"{kind}_")
    for cls, top in STAGE_TOPS.items():
        prefix = cls.cpp_kernel_name.removeprefix("prach_") + "_"
        add_system_steps(dag, harness(cls, workload="test"), work_dir=work_dir, top=top, prefix=prefix)
    return dag


if __name__ == "__main__":
    from waveflow.build.cli import PLATFORM_ARGS, platform_config, run_dag_cli

    run_dag_cli(lambda a: build_dag(), description=__doc__.splitlines()[0], default_through="compare",
                root_dir=HERE,
                extra_args=[(("--synth",), dict(choices=("build", "check"), default="build",
                             help="build: csynth a stale top; check: fail on one instead")),
                            *PLATFORM_ARGS],
                params_from_args=lambda a: {"synth": a.synth},
                config_from_args=lambda a: platform_config(a, part=RFSOC4X2_PART,
                                                           clk_freq=1e9 / RFSOC4X2_PERIOD_NS))
