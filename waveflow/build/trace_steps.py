"""BuildSteps for the timing-trace rung: name the nets, run the RTL, extract the timing.

The chain, all four of which are DAG steps:

    CodegenTbStep -> AddVcdTopStep + TraceManifestStep -> RtlSimStep -> ExtractBurstsStep
                     (the dumper)   (the net names)      (the VCD)     (the timing table)

The first two are pure ``elaborate()`` and cost nothing; the third needs Vitis + Vivado; the fourth
is pure waveform analysis.  ``ExtractBurstsStep``'s output is deliberately shaped as a *calibration
table* -- one row per firing with ``{nwords, num_trans, span}`` -- because that is both what the
figures need and what a ``CalibModel`` regresses over.  See ``plans/memcpy_timing_calibration.md``.

The manifest maps the Python graph onto the RTL net names a waveform will carry (see
:meth:`~waveflow.build.composite_gen.TopSpec.trace_manifest`).  Kept in its own module for the same
reason :mod:`waveflow.build.cosim_steps` is: one small concern with one consumer
(:mod:`waveflow.utils.trace`), and burying it in the C++ codegen module would suggest it emits C++.
"""
from __future__ import annotations

import json
import os
import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, ClassVar

from waveflow.build.build import BuildConfig, BuildStep
from waveflow.build.composite_gen import DEFAULT_MEM_DW, composite_top_spec
from waveflow.build.elaborate import elaborate
from waveflow.build.hwgen import cpp_kernel_name


def xsi_runner_name(os_name: str | None = None) -> str:
    """
    Name of the XSI runner script for ``os_name`` (defaults to this host's ``os.name``).

    Both scripts are copied into every ``xsi/`` workspace by
    :class:`~waveflow.build.streamutils.XsiHarnessStep`; only one of them runs on a given host.
    """
    return "run.bat" if (os_name or os.name) == "nt" else "run.sh"


#: The runner for the host importing this module — the common case, kept as a constant so error
#: messages and skip reasons can name the script the reader will actually look for.
XSI_RUNNER = xsi_runner_name()


def xsi_runner_cmd(
    top: str,
    tb: str,
    trace: bool = False,
    os_name: str | None = None,
) -> list[str]:
    """
    Build the argv that drives one XSI run, for whichever platform this is.

    ``run.bat`` needs ``cmd /c`` because a batch file is not directly executable; ``run.sh`` is
    invoked through ``bash`` rather than as ``./run.sh`` because the harness is copied out as file
    *text* by the build step, which does not preserve the executable bit.

    Parameters
    ----------
    top : str
        Kernel top name, as ``xelab -s`` names the snapshot.
    tb : str
        Testbench basename, without extension.
    trace : bool, optional
        Pass the runner's ``trace`` argument, elaborating the VCD dumper as a second top.
    os_name : str | None, optional
        Override the platform, in :data:`os.name` spelling. Exists so both forms stay testable
        from either host; leave it ``None`` in production callers.

    Returns
    -------
    list[str]
        Argument vector to hand to :func:`subprocess.run`, with ``cwd`` set to the ``xsi/`` dir.
    """
    runner = xsi_runner_name(os_name)
    args = [top, tb] + (["trace"] if trace else [])
    if (os_name or os.name) == "nt":
        return ["cmd", "/c", f".\\{runner}"] + args
    return ["bash", runner] + args


#: The dumper module.  One line of Verilog does the work; the comment is most of it, because the
#: LEVEL is the non-obvious part and a future reader will otherwise "fix" it to 0.
_DUMPER_TEMPLATE = '''\
// GENERATED by waveflow.build.trace_steps.AddVcdTopStep -- do not edit.
//
// Elaborated as a SECOND top alongside `{top}` (see run.bat's `trace` argument), so the XSI
// top -- and therefore every BFM port number -- is untouched.
//
// Level 1 = this scope's OWN signals, no descent into children.  That is already enough: Vitis
// lifts inter-task dataflow channel wires up into the top scope beside the task instances, so the
// internal FIFOs are reachable with no hierarchical path.  Level 0 would dump the whole subtree
// for no extra reach.
//
// The module and file are named after the top because one xsi/ directory can serve several tops,
// and a dumper naming a scope that is not elaborated is an error.
`timescale 1 ns / 1 ps

module vcd_dumper_{top};
    initial begin
        $dumpfile("{top}_trace.vcd");
        $dumpvars(1, {top});
    end
endmodule
'''


@dataclass(kw_only=True)
class AddVcdTopStep(BuildStep):
    """Write ``vcd_dumper_<top>.v`` -- the second elaborated top that dumps the waveform.

    XSI resolves only TOP-LEVEL ports, so an internal ``hls::stream`` is unreachable through its
    value API.  A ``$dumpvars`` module elaborated *alongside* the DUT sidesteps that without
    touching the DUT: the XSI top is unchanged, so every BFM port number and every gate cycle count
    stays exactly as it was.

    Naming the module and file after the top is not cosmetic.  One ``xsi/`` directory can serve
    several tops (``examples/interleaver/xsi`` builds three), and a dumper referring to a scope that
    is not part of *this* elaboration is a hard error -- so there is one dumper per top, and
    ``run.bat`` picks it with ``vcd_dumper_%TOP%.v``.

    Pairs with :class:`TraceManifestStep`: this produces the waveform, that names what is in it.
    """

    description: str = "Emit the $dumpvars second-top module for a traced XSI run."
    params: ClassVar[dict] = {}

    comp_class: type
    source_artifact: str
    output_dir: str = "xsi"
    #: The module xsim actually elaborates, when that is NOT the kernel.  A design whose memory lives
    #: beside the kernel is elaborated as its WRAPPER (``bram_simple_top``), and both the dumper's
    #: file name and the scope it names have to follow: `run.bat` picks ``vcd_dumper_%TOP%.v``, and a
    #: ``$dumpvars`` naming a scope that is not part of this elaboration is a hard error.  Left
    #: ``None`` for the ordinary case, where the kernel is the top.
    top: str | None = None

    def __post_init__(self) -> None:
        super().__post_init__()
        # The top name is a property of the CLASS, so no elaborate() here -- `produces` is read at
        # DAG-construction time and should not pay for a build.  It is also independent of the bus
        # width, which is why this step takes no width at all.
        self._top = self.top or cpp_kernel_name(self.comp_class)

    @property
    def consumes(self) -> list:  # type: ignore[override]
        return [self.source_artifact]

    @property
    def produces(self) -> dict:  # type: ignore[override]
        return {"vcd_dumper": Path(self.output_dir) / f"vcd_dumper_{self._top}.v"}

    def run(self, config: BuildConfig, **artifacts) -> dict[str, Any]:
        root_dir = Path(config.root_dir) if config.root_dir is not None else Path.cwd()
        out_path = root_dir / self.output_dir / f"vcd_dumper_{self._top}.v"
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(_DUMPER_TEMPLATE.format(top=self._top), encoding="utf-8")
        return {"vcd_dumper": out_path}


@dataclass(kw_only=True)
class TraceManifestStep(BuildStep):
    """Write ``<top>_trace.json`` -- the RTL net names for this component's channels and ports.

    The artifact is what lets a timing/waveform consumer bind to a VCD by exact name instead of
    guessing.  Binding by substring is actively wrong on these traces: an interleaver waveform holds
    both ``ywords_fifo_cap`` and ``il_store_..._U0_ywords_fifo_cap``, which differ in width and
    meaning.

    Consuming ``source_artifact`` (the design's Python source) is what makes the DAG regenerate the
    manifest when the graph changes -- the same dependency :class:`~waveflow.build.hwcodegen_steps.
    HlsCodegenStep` declares, and for the same reason.  There is no RTL input by design: the whole
    point is that these names are known before anything is synthesized.

    Construction parameters
    -----------------------
    comp_class : type
        The component to elaborate.  A composite gives channels; a leaf gives ports and one task.
    source_artifact : str
        Upstream artifact naming the design's Python source, for staleness.
    output_path : str
        Repo-relative location of the produced JSON.
    elab_params : dict | None
        Compile-time ``HwParam`` overrides for :func:`elaborate`.  Named ``elab_params`` because
        ``params`` is already a :class:`BuildStep` class attribute.

    The bus width is a DAG **param** (``mem_dwidth``), not a constructor argument, so a build run
    with ``--mem-dwidth 32`` cannot end up with a manifest that claims 64 -- the channel widths in
    it are what tells the loader where a ``framed_word``'s ``last`` bit sits.
    """

    description: str = "Emit the trace manifest (RTL net names) for a component."
    params: ClassVar[dict] = {"mem_dwidth": DEFAULT_MEM_DW}

    comp_class: type
    source_artifact: str
    output_path: str = "results/trace_manifest.json"
    elab_params: dict[str, Any] | None = field(default=None)

    @property
    def consumes(self) -> list:  # type: ignore[override]
        return [self.source_artifact]

    @property
    def produces(self) -> dict:  # type: ignore[override]
        return {"trace_manifest": Path(self.output_path)}

    def run(self, config: BuildConfig, mem_dwidth=DEFAULT_MEM_DW, **artifacts) -> dict[str, Any]:
        comp = elaborate(self.comp_class, self.elab_params)
        manifest = composite_top_spec(comp, width=int(mem_dwidth)).trace_manifest()

        root_dir = Path(config.root_dir) if config.root_dir is not None else Path.cwd()
        out_path = root_dir / self.output_path
        out_path.parent.mkdir(parents=True, exist_ok=True)
        # sort_keys so the artifact is byte-stable across runs: an unstable artifact would make the
        # DAG think the design changed on every build.
        out_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n",
                            encoding="utf-8")
        return {"trace_manifest": out_path}


@dataclass(kw_only=True)
class RtlSimStep(BuildStep):
    """Run the RTL through XSI **with tracing on**, producing ``<top>_trace.vcd``.

    A thin wrapper over the example's ``xsi/run.bat``, which already does the whole flow
    (``xvlog`` -> ``xelab -dll`` -> ``g++`` the BFM main -> execute).  Its third argument ``trace``
    additionally elaborates the :class:`AddVcdTopStep` dumper as a second top, leaving the DUT and
    every BFM port number untouched -- the cycle counts are identical either way.

    **This step asserts nothing.**  It runs and produces an artifact; correctness stays with the
    ``-m xsi`` gate in ``tests/examples/test_xsi_bfm.py``, which calls ``run.bat`` directly and
    checks the exact cycle count.  Two callers of one script is deliberate: routing a green gate
    through new code is how a gate quietly stops meaning what it meant.

    Toolchain-gated: needs Vitis-synthesized RTL on disk plus Vivado ``xsim`` and a MinGW ``g++``.

    Construction parameters
    -----------------------
    top, tb : str
        Kernel top and BFM testbench basename, exactly as ``run.bat`` takes them.
    xsi_dir : str
        Directory holding ``run.bat`` (repo-relative).
    tb_artifact : str
        Artifact of the step that GENERATES ``<tb>.cpp`` and its harness.  ``run.bat`` recompiles
        whatever ``.cpp`` is on disk, so without this edge the TB codegen step is not in this
        step's dependency closure: ``--through extract_bursts`` skips it entirely, and every point
        of a sweep runs the RTL against the **last-generated** testbench.

        That is not a hypothetical either.  The harness carries the scenario's arena size and its
        ``h.run(N)`` cycle bound, so a sweep silently ran every point under the committed gate's
        3400-cycle bound: the larger points were cut off mid-job and the missing firings read as a
        *design stall* -- see ``plans/sweep_runner.md``.  Forcing the codegen step does not help,
        because a step outside the closure is never consulted, forced or not.
    prepare : callable | None
        Called as ``prepare(xsi_dir, config)`` before the run, to materialize the scenario bundles the
        BFM reads (for mem_copy, ``write_mem_copy_xsi_bundles``).  The scenario is an *input* to the
        run, so a step that did not write it would measure whatever was left behind.

        It receives the :class:`BuildConfig` because under a **sweep** the scenario is the thing that
        varies: :class:`~waveflow.build.sweep.SweepRunner` calls a *zero-argument* dag factory and
        delivers the point through ``config.params``, so a ``prepare`` closed over one scenario at
        construction time would write the same vectors at every point -- and the run would then be
        measured against the wrong ones.  That failure has a precedent here: see the note in
        :meth:`run` about the stale VCD, which produced an identical period at five different job
        sizes before it was caught.
    """

    description: str = "Run the RTL under XSI with $dumpvars tracing enabled."
    params: ClassVar[dict] = {}

    top: str
    tb: str
    xsi_dir: str = "xsi"
    rtl_artifact: str = "report_dir"
    dumper_artifact: str = "vcd_dumper"
    tb_artifact: str = "tb_main"
    prepare: Callable[[Path, "BuildConfig"], None] | None = None

    @property
    def consumes(self) -> list:  # type: ignore[override]
        return [self.rtl_artifact, self.dumper_artifact, self.tb_artifact]

    @property
    def produces(self) -> dict:  # type: ignore[override]
        return {"trace_vcd": Path(self.xsi_dir) / f"{self.top}_trace.vcd"}

    def run(self, config: BuildConfig, **artifacts) -> dict[str, Any]:
        root = Path(config.root_dir) if config.root_dir is not None else Path.cwd()
        xsi = root / self.xsi_dir
        vcd = xsi / f"{self.top}_trace.vcd"

        if self.prepare is not None:
            self.prepare(xsi, config)

        # Delete first, then require it to reappear.  Re-running the built .exe does NOT regenerate
        # the VCD -- only the full run.bat path, which re-elaborates, does -- so without this guard
        # a failed or skipped run leaves the PREVIOUS trace on disk and everything downstream is
        # silently measured from the wrong run.  Not hypothetical: it yielded an identical period
        # at five different job sizes before it was caught.
        vcd.unlink(missing_ok=True)

        r = subprocess.run(xsi_runner_cmd(self.top, self.tb, trace=True),
                           cwd=str(xsi), capture_output=True, text=True, timeout=1800)
        out = (r.stdout or "") + (r.stderr or "")
        if "XSI_EXITCODE=0" not in out:
            raise RuntimeError(f"{self.top}: XSI run did not complete cleanly:\n{out[-3000:]}")
        if not vcd.exists():
            raise RuntimeError(
                f"{self.top}: {XSI_RUNNER} completed but wrote no {vcd.name}. Is "
                f"vcd_dumper_{self.top}.v present in {xsi} (AddVcdTopStep), and did "
                f"{XSI_RUNNER} get the `trace` argument?")
        return {"trace_vcd": vcd}


@dataclass(kw_only=True)
class ExtractBurstsStep(BuildStep):
    """Turn a traced run into a **timing table**: one row per component firing.

    Binds the :class:`TraceManifestStep` manifest to the :class:`RtlSimStep` waveform and writes
    what the figures and the calibration both need:

    * ``firings`` -- per firing: ``span`` (first input handshake -> ``ap_done``), the regression
      features ``nwords`` (m_axi beats moved) and ``num_trans`` (burst count), and ``blocked``
      (cycles its output channel sat at capacity).
    * ``channels`` -- per internal channel, packet and beat counts on both ends.
    * ``boundary`` -- per port / bundle, burst and beat counts.

    ``span`` is anchored on ``ap_done``, not on the last output beat, because an ``m_axi`` store is
    posted: a component keeps working after its final stream beat.  On mem_copy's writer that is
    155 vs 183 -- a 15% under-count that inverts which stage looks like the bottleneck.  See
    :class:`waveflow.utils.trace.Firing`.

    Pure waveform analysis: no toolchain, no simulation.
    """

    description: str = "Extract a per-firing timing table from a traced RTL run."
    params: ClassVar[dict] = {}

    manifest_artifact: str = "trace_manifest"
    vcd_artifact: str = "trace_vcd"
    output_path: str = "results/timing_events.json"
    #: Words per AXI burst -- HLS's ``max_read_burst_length`` / ``max_write_burst_length``.
    #: Recorded so a consumer can CHECK ``num_trans`` against ``ceil(nwords / max_burst_len)``
    #: rather than assume it.
    max_burst_len: int = 16
    #: How many firings each task is expected to complete -- the job count the scenario issued, as an
    #: int or a ``callable(config) -> int`` when a sweep varies it.  ``None`` disables the check.
    expect_firings: "int | Callable[[BuildConfig], int] | None" = None

    @property
    def consumes(self) -> list:  # type: ignore[override]
        return [self.manifest_artifact, self.vcd_artifact]

    @property
    def produces(self) -> dict:  # type: ignore[override]
        return {"timing_events": Path(self.output_path)}

    def _firing_rows(self, bt) -> list[dict]:
        rows: list[dict] = []
        for task in bt.manifest["tasks"]:
            view = bt.component(task["inst"])
            try:
                firings = bt.component_firings(task["inst"])
            except ValueError:
                continue                      # a source with no observable input has no window
            out_ch = [c for c in view.outputs if bt.channel(c)["kind"] != "sob"]
            maxi = [bt.port(p) for p in view.boundary if bt.port(p)["kind"] == "maxi"]

            for f in firings:
                nwords = num_trans = 0
                for p in maxi:
                    s = p["signals"]
                    for beat_v, beat_r, addr_v, addr_r in (
                            ("RVALID", "RREADY", "ARVALID", "ARREADY"),
                            ("WVALID", "WREADY", "AWVALID", "AWREADY")):
                        if beat_v not in s or addr_v not in s:
                            continue
                        beats = bt._handshakes(s[beat_v], s[beat_r])
                        addrs = bt._handshakes(s[addr_v], s[addr_r])
                        nwords += int(((beats >= f.start) & (beats <= f.end)).sum())
                        num_trans += int(((addrs >= f.start) & (addrs <= f.end)).sum())
                rows.append({
                    "component": task["id"], "inst": task["inst"], "index": f.index,
                    "start": f.start, "end": f.end, "span": f.span,
                    "nwords": nwords, "num_trans": num_trans,
                    "blocked": sum(bt.channel_blocked(c, f.start, f.end) for c in out_ch),
                })
        return rows

    def _check_coverage(self, rows: list[dict], config: BuildConfig) -> None:
        """Refuse a table that is missing firings the scenario issued.

        mem_copy at ``n_words=1024`` produced ``seq=3, reader=2, writer=2`` for a four-job scenario.
        Every span in it was correct, which is what makes it dangerous: nothing upstream objects,
        because :class:`RtlSimStep` asserts nothing by design and the golden that passes in the log
        is the *pysim's*.  The measurement looks like a clean point and is half a point.

        The check deliberately does **not** name a cause.  The obvious guess -- the harness cycle
        bound ran out -- was wrong on the very case that motivated it: the bound was 5404, the last
        ``ap_done`` landed at 2405, and the waveform then ran on for some four thousand idle cycles.
        A short table means the design stopped firing, and whether that is a tight bound, a stall or
        a scenario that never delivered the later jobs is what the reader has to go and find out.

        That matters most exactly where it is least visible.  A sweep files this table as a corpus
        row; a short point does not fail, it silently narrows the evidence a residual is fitted from,
        and the fit still reports a tiny error because the rows that survived are individually right.

        Left as a count comparison rather than "all components agree": a design may legitimately fire
        one stage more often than another, and a check that guesses would either miss the truncation
        or reject a correct design.  The scenario knows the number; it should say it.
        """
        want = self.expect_firings
        if want is None:
            return
        want = int(want(config) if callable(want) else want)

        got: dict[str, int] = {}
        for r in rows:
            got[r["component"]] = got.get(r["component"], 0) + 1
        short = {c: n for c, n in got.items() if n != want}
        if short:
            raise RuntimeError(
                f"incomplete trace: expected {want} firing(s) per task, got "
                f"{ {c: n for c, n in sorted(got.items())} }. The design stopped firing before the "
                f"scenario finished. Check, in this order: the last ap_done cycle against the "
                f"harness bound (a tight bound truncates; a large gap means it stalled instead), "
                f"then whether the later jobs' data reached the DUT at all. "
                f"Off by count: {sorted(short)}")

    def run(self, config: BuildConfig, **artifacts) -> dict[str, Any]:
        from waveflow.utils.trace import load_trace

        bt = load_trace(artifacts[self.manifest_artifact], artifacts[self.vcd_artifact])
        man = bt.manifest

        channels = []
        for c in man["channels"]:
            row = {"id": c["id"], "kind": c["kind"], "width": c["width"],
                   "producer": c["producer"], "consumer": c["consumer"]}
            if c["kind"] != "sob":
                for side in ("write", "read"):
                    pk, _ = bt.channel_bursts(c["id"], side=side)
                    row[side] = {"packets": len(pk),
                                 "beats": int(sum(len(p["data"]) for p in pk))}
            channels.append(row)

        boundary = []
        for p in man["boundary"]:
            if p["kind"] == "maxi":
                wb, rb, _ = bt.aximm_bursts(p["id"])
                boundary.append({
                    "id": p["id"], "kind": "maxi", "directions": p["directions"],
                    "write": {"bursts": len(wb),
                              "beats": int(sum(len(b["data"]) for b in wb))},
                    "read": {"bursts": len(rb),
                             "beats": int(sum(len(b["data"]) for b in rb))}})
            else:
                bursts, _ = bt.port_bursts(p["id"])
                boundary.append({"id": p["id"], "kind": p["kind"], "bursts": len(bursts),
                                 "beats": int(sum(len(b["data"]) for b in bursts))})

        rows = self._firing_rows(bt)
        # Before writing, not after: a short table that reached disk is one a later step can pick up
        # and file as a corpus row, and the raise would then be about a run nobody is looking at.
        self._check_coverage(rows, config)

        events = {"version": 1, "top": man["top"], "max_burst_len": self.max_burst_len,
                  "firings": rows, "channels": channels, "boundary": boundary}

        root = Path(config.root_dir) if config.root_dir is not None else Path.cwd()
        out_path = root / self.output_path
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(json.dumps(events, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        return {"timing_events": out_path}


def rtl_staleness(example_root, top: str, *, gen_dir: str = "gen",
                  include_dir: str = "include") -> str | None:
    """``None`` if *top*'s synthesized RTL is at least as new as everything it was built from,
    otherwise a sentence naming the offending source.

    **Why this exists, twice over.**  ``<example>/<top>_proj/`` is gitignored *build output*, so
    which build produced the files on disk is decided by whatever ran csynth last in this working
    tree â€” possibly on another branch, against sources this checkout does not contain.  Two separate
    gates have already reported that as a *behaviour change*:

    * ``test_rf_samp_buf_fire_cycles`` read ``<Latency>undef</Latency>`` from a branch that
      pipelined the bodies and failed three ways on ``main``;
    * three XSI gates reported off-by-one cycle counts (4211 vs 4210, 15442 vs 15441) against RTL
      dated three days earlier, and rebuilding each example restored its recorded number exactly.

    Both times the number was right and the *artifact* was wrong, and a cycle gate that says "this is
    a real behaviour change, re-record it" when it is looking at somebody else's RTL is worse than no
    gate â€” it invites exactly the one edit that must never be made on a whim.

    ``git checkout`` stamps a checked-out file with the checkout time, so a branch switch makes the
    sources newer than any RTL built before it: the case that actually bit is the case this catches.

    Deliberately a **predicate**, not an assertion or a rebuild.  A gate decides for itself whether
    to skip; rebuilding here would hide a 40-second csynth inside a test fixture, and a helper that
    silently runs the toolchain is its own kind of surprise.
    """
    from pathlib import Path

    root = Path(example_root)
    rtl_dir = root / f"{top}_proj" / "solution1" / "syn" / "verilog"
    if not rtl_dir.is_dir():
        return None                      # absent is the caller's business, not staleness
    rtl = [p for p in rtl_dir.glob("*.v")]
    if not rtl:
        return None
    newest_rtl = max(p.stat().st_mtime for p in rtl)

    sources: list = []
    gen = root / gen_dir / f"{top}.cpp"
    if gen.is_file():
        sources.append(gen)
    inc = root / include_dir
    if inc.is_dir():
        sources += [p for p in inc.iterdir() if p.suffix in (".h", ".hpp", ".cpp")]
    for src in sources:
        if src.stat().st_mtime > newest_rtl + 1.0:     # 1 s slack: filesystem timestamp grain
            return (f"{src.relative_to(root)} is newer than the newest RTL in "
                    f"{rtl_dir.relative_to(root)} â€” the synthesized design on disk is not this "
                    f"checkout's. Re-run the example's build --through csynth. Do NOT re-record a "
                    f"cycle count against RTL you did not produce.")
    return None
