"""mm_writer_gen.py — the free-running tops of a routed credit stream's bus writers.

``plans/mm_credit_stream.md`` Stage 3.  :class:`~waveflow.hw.mm_credit.MmStreamWriter` is framework
code with a FIXED body (``waveflow/build/mm_stream_writer_task.h``): one ``hls::task`` per writer, a
stream in, an ``m_axi`` out, and a ``target`` -- the view's word index on the bus -- as a stable
``ap_none`` input the system top drives.  The composite generator lowers streams and memory ports but
not a scalar, so the top is rendered here; there are only two shapes.

    write_writer_project(root, "queue", dw=64, maxp=64)    # -> gen/mm_queue_writer_64_64.cpp + .tcl
    write_writer_project(root, "credit", dw=64)            # -> gen/mm_credit_writer_64.cpp + .tcl
"""
from __future__ import annotations

from pathlib import Path

from waveflow.build.composite_gen import GEN_DIR, render_tcl, tcl_path

#: The fixed body, copied into a design's ``include/`` beside its other task bodies.
TASK_HEADER = Path(__file__).resolve().parent / "mm_stream_writer_task.h"


def writer_top_name(mode: str, dw: int, maxp: int | None = None) -> str:
    if mode == "queue":
        return f"mm_queue_writer_{int(dw)}_{int(maxp)}"
    if mode == "credit":
        return f"mm_credit_writer_{int(dw)}"
    raise ValueError(f"mode must be 'queue' or 'credit', got {mode!r}")


def render_writer_top(mode: str, dw: int, maxp: int | None = None) -> str:
    """The top ``.cpp``: ``s_in`` (AXIS -- with a TLAST pin in queue mode, where it delimits a
    packet), ``m_mem`` (``m_axi`` on ``gmem0``, base register left at 0), ``target`` (``ap_none``,
    stable)."""
    name = writer_top_name(mode, dw, maxp)
    if mode == "queue":
        if maxp is None:
            raise ValueError("a queue writer needs maxp (the longest packet: the queue's depth)")
        s_in = f"hls::stream<streamutils::axi4s_word<{dw}> >& s_in"
        task = f"mm_queue_writer_task<{dw}, {int(maxp)}>"
    else:
        s_in = f"hls::stream<ap_uint<{dw}> >& s_in"
        task = f"mm_credit_writer_task<{dw}>"
    return f"""// {name}.cpp -- GENERATED by waveflow (build/mm_writer_gen.py).  DO NOT EDIT.
// A routed credit stream's {mode} writer: a free-running (ap_ctrl_none) hls::task over the fixed body
// in mm_stream_writer_task.h.  `target` is the view's bus word index, driven by the system top.
#include "hls_task.h"
#include "hls_stream.h"
#include <ap_int.h>
#include "streamutils_hls.h"
#include "mm_stream_writer_task.h"

void {name}(
    {s_in},
    ap_uint<{dw}>* m_mem,
    ap_uint<32> target
) {{
#pragma HLS INTERFACE axis port=s_in
#pragma HLS INTERFACE m_axi port=m_mem offset=slave bundle=gmem0 depth=8192
#pragma HLS INTERFACE ap_none port=target
#pragma HLS stable variable=target
#pragma HLS INTERFACE ap_ctrl_none port=return
    hls_thread_local hls::task t0({task}, s_in, m_mem, target);
}}
"""


def write_writer_project(root, mode: str, dw: int, maxp: int | None = None) -> str:
    """Render the top and its csynth script into ``<root>/gen`` (run the script with ``work_dir=root``);
    copy the fixed body into ``<root>/include``.  Returns the top name."""
    root = Path(root)
    name = writer_top_name(mode, dw, maxp)
    (root / GEN_DIR).mkdir(parents=True, exist_ok=True)
    (root / GEN_DIR / f"{name}.cpp").write_text(render_writer_top(mode, dw, maxp), encoding="utf-8")
    tcl_path(root, name).write_text(render_tcl(name), encoding="utf-8")
    inc = root / "include"
    inc.mkdir(parents=True, exist_ok=True)
    (inc / TASK_HEADER.name).write_text(TASK_HEADER.read_text(encoding="utf-8"), encoding="utf-8")
    return name
