"""system_ooc.py — a system synthesized per device and linked: route B's synthesis (``ooc_link``).

``plans/ip_packaging_routes.md`` Stage 1.  :mod:`~waveflow.build.system_synth` synthesizes a system
top **globally**: one run, optimizing across every boundary.  This module synthesizes it the way a
block design of packaged IPs is synthesized by default:

1. each **sub-top** -- each device and the memory (``SystemTopSpec.subs``, rendered alone by
   :meth:`~waveflow.build.system_top.SystemTopSpec.render_sub_verilog`) -- out of context, keeping
   its netlist (:func:`~waveflow.build.rtl_ooc.synth_rtl_ooc`, cached by the content of everything it
   reads, so an unchanged device is never re-synthesized);
2. the **system top** with each sub-top as a black box: the crossbar and the glue, out of context
   (cached the same way: a device change does not re-synthesize the crossbar);
3. the **link**: the top's netlist and each sub-top's, scoped to its cell, joined by ``link_design``,
   then ``opt_design`` -- the cross-boundary cleanup a linked design still gets.

Four numbers come out, and they are what the plan compares with the global synthesis:

* **parts** -- each sub-top's own out-of-context counters;
* **top** -- the top's own run (crossbar and glue, sub-tops empty);
* **linked** -- the total after the link and ``opt_design``;
* **link term** -- ``linked - (top + Σ parts)``: what linking recovered (negative) or added.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path


@dataclass
class OocLink:
    """One per-device synthesis of a system, linked."""

    top: str
    part: str
    period_ns: float
    parts: dict = field(default_factory=dict)        # sub-top name -> counters
    part_seconds: dict = field(default_factory=dict)  # sub-top name -> synth_design seconds
    part_cached: dict = field(default_factory=dict)   # sub-top name -> True if no Vivado ran
    top_counters: dict = field(default_factory=dict)  # the top alone: crossbar + glue
    linked: dict = field(default_factory=dict)        # after read_checkpoint -cell + opt_design
    top_seconds: float = 0.0                          # the top's synth_design
    top_cached: bool = False                          # True if the top's run was a cache hit
    link_seconds: float = 0.0                         # read_checkpoint + opt_design
    wall_seconds: float = 0.0                         # the whole call, Vivado start-ups included
    tool: str = ""

    @property
    def link_term(self) -> dict:
        """``linked - (top + Σ parts)`` per counter."""
        keys = set(self.linked) | set(self.top_counters) | {k for c in self.parts.values() for k in c}
        return {k: int(self.linked.get(k, 0)) - int(self.top_counters.get(k, 0))
                - sum(int(c.get(k, 0)) for c in self.parts.values()) for k in sorted(keys)}

    def to_json(self) -> dict:
        d = asdict(self)
        d["link_term"] = self.link_term
        return d


def black_box(module_text: str) -> str:
    """A ``(* black_box *)`` stub of the module in *module_text*: its port list, no body -- what the
    top is synthesized against while the sub-top's own netlist waits to be linked in."""
    m = re.search(r"^module (\w+) \((.*?)\);", module_text, re.M | re.S)
    if m is None:
        raise ValueError("no module header in the text")
    return f"(* black_box *)\nmodule {m.group(1)} ({m.group(2)});\nendmodule\n"


def top_with_black_boxes(spec) -> str:
    """The system top's module with each sub-top a black box: the top's own synthesis input."""
    from waveflow.build.system_top import _render_modules

    mods = _render_modules(spec)
    return ("// GENERATED by waveflow (build/system_ooc.py): the top, sub-tops as black boxes.\n"
            "`timescale 1ns/1ps\n\n" + "".join(black_box(mods[s.name]) + "\n" for s in spec.subs)
            + mods[""])


def top_tcl(top: str, *, part: str, xci: str, top_v: str) -> str:
    """Synthesize the top -- the crossbar and the glue -- against the black boxes, out of context,
    and keep its netlist (``top.dcp``)."""
    return "\n".join([
        f"create_project -in_memory -part {part}",
        "set_property target_language Verilog [current_project]",
        f"read_ip {{{xci}}}",
        f"set_property generate_synth_checkpoint false [get_files {{{xci}}}]",
        f"generate_target all [get_files {{{xci}}}]",
        f"read_verilog {{{top_v}}}",
        "read_xdc clocks.xdc",
        "set t0 [clock milliseconds]",
        f"synth_design -top {top} -part {part} -mode out_of_context",
        "set t1 [clock milliseconds]",
        "report_utilization -file util_top.rpt",
        "write_checkpoint -force top.dcp",
        'puts "WF_SECONDS [expr {($t1 - $t0) / 1000.0}]"',
        'puts "WF_VERSION [version -short]"',
        'puts "WF_DONE 1"',
    ]) + "\n"


def link_tcl(top: str, *, part: str, top_dcp: str, cells: dict[str, str]) -> str:
    """Link the top's netlist with each sub-top's, scoped to its cell (Vivado's bottom-up flow:
    ``add_files`` + ``SCOPED_TO_CELLS`` + ``link_design``), run ``opt_design``, report.  *cells* maps
    a cell (sub-top instance) to its checkpoint.  (``read_checkpoint -cell`` into the design
    ``synth_design`` leaves open is refused -- "no structural source files" -- so the link is its own
    project.)"""
    lines = [f"create_project -in_memory -part {part}", f"add_files {{{top_dcp}}}"]
    for cell, dcp in cells.items():
        lines += [f"add_files {{{dcp}}}",
                  f"set_property SCOPED_TO_CELLS {{{cell}}} [get_files {{{dcp}}}]"]
    lines += [
        "set t0 [clock milliseconds]",
        f"link_design -top {top} -part {part} -mode out_of_context",
        "opt_design",
        "set t1 [clock milliseconds]",
        "report_utilization -file util_linked.rpt",
        'puts "WF_SECONDS [expr {($t1 - $t0) / 1000.0}]"',
        'puts "WF_VERSION [version -short]"',
        'puts "WF_DONE 1"',
    ]
    return "\n".join(lines) + "\n"


def _vivado(vivado, work: Path, tcl_name: str, what: str) -> dict:
    from waveflow import events
    from waveflow.utils.vivado_report import parse_markers

    with events.span("tool", "vivado", script=tcl_name):
        r = subprocess.run([vivado, "-mode", "batch", "-nojournal", "-log", "vivado.log",
                            "-source", tcl_name], cwd=str(work), capture_output=True, text=True,
                           timeout=7200)
    out = (r.stdout or "") + (r.stderr or "")
    (work / "vivado_stdout.txt").write_text(out, encoding="utf-8")
    mk = parse_markers(out)
    if r.returncode != 0 or "DONE" not in mk:
        raise RuntimeError(f"{what} failed:\n{out[-4000:]}")
    return mk


def synth_ooc_link(spec, *, kernel_dirs: dict[str, Path], ip, part: str, period_ns: float,
                   out_dir: str | Path, vivado: str | None = None,
                   force: bool = False) -> OocLink:
    """Synthesize *spec* per sub-top out of context, the top against black boxes, and link
    (module doc).  *kernel_dirs* maps each csynth'd module to its ``syn/verilog``; *ip* is the
    crossbar IP generated for *part*.  Each sub-top run is cached by the content of everything it
    reads (:func:`~waveflow.build.rtl_ooc.synth_rtl_ooc`), and so is the top's run (its black-box
    text and the crossbar's configuration), so a change to one device re-synthesizes that device
    and re-links -- nothing else.  The link always runs."""
    import hashlib

    from waveflow.build.rtl_ooc import synth_rtl_ooc
    from waveflow.utils.vivado_report import parse_utilization

    t_start = time.perf_counter()
    out_dir = Path(out_dir)
    res = OocLink(top=spec.top, part=part, period_ns=float(period_ns))
    cells: dict[str, str] = {}
    for sub in spec.subs:
        src = out_dir / "src"
        src.mkdir(parents=True, exist_ok=True)
        sub_v = src / f"{sub.module}.v"
        sub_v.write_text(spec.render_sub_verilog(sub.name), encoding="utf-8")
        leaves, kernels = spec.sources_of(sub.name)
        sources = [sub_v, *leaves] + [f for m in kernels
                                      for f in sorted(Path(kernel_dirs[m]).glob("*.v"))]
        t0 = time.perf_counter()
        r = synth_rtl_ooc(sub.module, {}, sources, part=part, period_ns=period_ns,
                          out_dir=out_dir / "parts", vivado=vivado, force=force, checkpoint=True)
        res.part_cached[sub.name] = (time.perf_counter() - t0) < 1.0
        res.parts[sub.name] = r.counters
        res.part_seconds[sub.name] = r.seconds
        cells[sub.inst] = r.checkpoint

    if vivado is None:
        from waveflow.toolchain.toolchain import find_vivado_path
        vivado = find_vivado_path()
    if not vivado:
        raise RuntimeError("synth_ooc_link: Vivado not found (set WAVEFLOW_VIVADO_PATH or PATH)")

    # The top: cached by its black-box text, the crossbar's configuration, the part and the clock.
    top_text = top_with_black_boxes(spec)
    digest = hashlib.sha256("|".join([top_text.replace("\r\n", "\n"),
                                      json.dumps(spec.xbar.hw_params(), sort_keys=True),
                                      ip.module, part, f"{period_ns:g}"]).encode()).hexdigest()[:12]
    top_dir = out_dir / "top" / digest
    stamp = top_dir / "result.json"
    if stamp.exists() and (top_dir / "top.dcp").exists() and not force:
        cached = json.loads(stamp.read_text(encoding="utf-8"))
        res.top_counters, res.top_seconds = cached["counters"], cached["seconds"]
        res.top_cached = True
    else:
        if top_dir.exists():
            shutil.rmtree(top_dir)
        top_dir.mkdir(parents=True)
        ip_copy = top_dir / "ip" / ip.module           # generate_target rewrites files under the IP
        shutil.copytree(ip.root, ip_copy)
        (top_dir / f"{spec.top}.v").write_text(top_text, encoding="utf-8")
        (top_dir / "clocks.xdc").write_text(f"create_clock -period {period_ns:g} -name ap_clk "
                                            f"[get_ports ap_clk]\n", encoding="utf-8")
        (top_dir / "top.tcl").write_text(top_tcl(spec.top, part=part,
                                                 xci=(ip_copy / f"{ip.module}.xci").as_posix(),
                                                 top_v=f"{spec.top}.v"), encoding="utf-8")
        mk = _vivado(vivado, top_dir, "top.tcl", f"the top of {spec.top}, out of context")
        res.top_counters = parse_utilization((top_dir / "util_top.rpt").read_text(encoding="utf-8"))
        res.top_seconds = float(mk.get("SECONDS") or 0.0)
        stamp.write_text(json.dumps({"counters": res.top_counters, "seconds": res.top_seconds}),
                         encoding="utf-8")

    work = out_dir / "link"
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    (work / "link.tcl").write_text(link_tcl(spec.top, part=part,
                                            top_dcp=(top_dir / "top.dcp").resolve().as_posix(),
                                            cells=cells), encoding="utf-8")
    mk = _vivado(vivado, work, "link.tcl", f"the link of {spec.top}")
    res.linked = parse_utilization((work / "util_linked.rpt").read_text(encoding="utf-8"))
    res.link_seconds = float(mk.get("SECONDS") or 0.0)
    res.tool = f"vivado {mk.get('VERSION', '')}".strip()
    res.wall_seconds = time.perf_counter() - t_start
    (out_dir / "result.json").write_text(json.dumps(res.to_json(), indent=2), encoding="utf-8")
    return res


__all__ = ["OocLink", "black_box", "link_tcl", "synth_ooc_link", "top_tcl", "top_with_black_boxes"]
