"""vecmult_build.py — the VecMult build DAG.

The rungs, in the order the flow teaches them:

    source -> pysim -> codegen_dut -> csim -> csynth -> resources

``pysim`` needs no toolchain and runs in seconds.  ``csim`` replays that exact job through the
hand-written C++ and compares element for element -- the rung that makes "Python golden, C++ twin" a
checked claim rather than an intention, and the reason ``csynth`` consumes its verdict.  ``csynth``
produces every resource counter; ``resources`` attributes the report and files per-module records.

Deliberately **no XSI rung**: this example exists to measure *utilization*, and the counters are
settled at C-synthesis.  Cycle-accuracy is a different question needing a much more expensive gate
--- see ``examples/fir_block`` for a design that does both.

Driven by :func:`~waveflow.build.cli.run_dag_cli`, so ``--list-steps`` / ``--status`` / ``--through``
/ ``--force`` all work without this file implementing any of them::

    python -m examples.vecmult.vecmult_build --list-steps
    python -m examples.vecmult.vecmult_build --through pysim
    python -m examples.vecmult.vecmult_build --through resources --dwid 128 --vlen 4096
"""
from __future__ import annotations

import json
import shutil
import time as _time
from dataclasses import dataclass
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent

from waveflow.build.build import BuildConfig, BuildDag, BuildStep, SourceStep  # noqa: E402
from waveflow.build.cli import run_dag_cli  # noqa: E402
from waveflow.build.composite_gen import (  # noqa: E402
    GEN_DIR,
    composite_top_spec,
    render_tcl,
    render_top,
)
from waveflow.build.elaborate import elaborate  # noqa: E402
from waveflow.build.resource_steps import InspectSynthStep  # noqa: E402
from waveflow.build.streamutils import MemMgrStep, StreamUtilsStep  # noqa: E402
from waveflow.hw.arrayutils import _array_utils_namespace, gen_array_utils  # noqa: E402
from waveflow.hw.dataschema import DataSchemaStep  # noqa: E402
from waveflow.toolchain.toolchain import run_vitis_hls  # noqa: E402

from examples.vecmult.vecmult import (  # noqa: E402
    DEFAULT_DWID,
    DEFAULT_VLEN,
    INCLUDE_DIR,
    SAMP_W,
    Samp,
    VecCmd,
    VecMult,
    VecResp,
    lane_width,
    vec_type,
)

#: Schema classes the gen-include step emits C++ headers for: the command the body reads and the
#: response it writes.
SCHEMA_CLASSES = (VecCmd, VecResp)

TOP = "vec_mult"
PART = "xc7z020clg484-1"
PERIOD_NS = 10

#: Hand-written bodies: copied into ``include/``, never generated over.
HAND_WRITTEN_TASKS = ("vec_mult_task.h",)


def render_types_h() -> str:
    """The one derived header the hand-written body leans on.

    All it does is give the generated array-utils namespace a **stable** alias.  The generated name
    is a function of the element type (``int16_array_utils``), so a body naming it directly would
    break the moment the sample type changed; ``vm_au`` does not.
    """
    au_ns = _array_utils_namespace(Samp)
    return (
        "#ifndef WAVEFLOW_VECMULT_TYPES_H\n"
        "#define WAVEFLOW_VECMULT_TYPES_H\n"
        "// GENERATED by vecmult_build.render_types_h -- do not edit.\n"
        f'#include "{au_ns}.h"\n'
        "\n"
        f"namespace vm_au = {au_ns};\n"
        "\n"
        "#endif  // WAVEFLOW_VECMULT_TYPES_H\n"
    )


def gen_headers(config: BuildConfig, dwid: int = DEFAULT_DWID, vlen: int = DEFAULT_VLEN) -> None:
    """Emit the stream utilities, the memory manager, the payload schema and its array-utils."""
    dag = BuildDag()
    dag.add(StreamUtilsStep(output_dir=INCLUDE_DIR))
    dag.add(MemMgrStep(output_dir=INCLUDE_DIR))
    dag.add(DataSchemaStep(vec_type(vlen), word_bw_supported=[int(dwid)],
                           include_dir=INCLUDE_DIR))
    for cls in SCHEMA_CLASSES:
        dag.add(DataSchemaStep(cls, word_bw_supported=[int(dwid)], include_dir=INCLUDE_DIR))
    results = dag.run(config)
    failed = [n for n, r in results.items() if not r.success]
    if failed:
        raise RuntimeError(f"header generation failed: {failed}")
    gen_array_utils(Samp, [int(dwid)], cfg=config, streamutils_dir=INCLUDE_DIR)


def generate_dut(out_dir: Path = HERE, dwid: int = DEFAULT_DWID,
                 vlen: int = DEFAULT_VLEN) -> Path:
    """Headers, the stable-alias header, the sticky task body, the ``ap_ctrl_none`` top, the TCL."""
    out_dir = Path(out_dir)
    config = BuildConfig(root_dir=out_dir, params={})
    gen_headers(config, dwid=dwid, vlen=vlen)

    inc = out_dir / INCLUDE_DIR
    inc.mkdir(parents=True, exist_ok=True)
    (inc / "vecmult_types.h").write_text(render_types_h(), encoding="utf-8")
    # The testbench needs the same two knobs the top bakes into its task instantiation.  Emitted
    # rather than duplicated, so the TB cannot drift from the DUT it is checking.
    # The vector directory travels in the header too, as an absolute path with forward slashes.
    # Passing it as a -D through TCL does not survive the quoting on Windows, and csim runs from
    # <proj>/<solution>/csim/build, so a relative path would depend on that depth.
    data_dir = (out_dir / "data").resolve().as_posix()
    (inc / "vec_mult_params.h").write_text(
        "#ifndef WAVEFLOW_VEC_MULT_PARAMS_H\n"
        "#define WAVEFLOW_VEC_MULT_PARAMS_H\n"
        "// GENERATED by vecmult_build.generate_dut -- do not edit.\n"
        f"#define VM_DWID {int(dwid)}\n"
        f"#define VM_VLEN {int(vlen)}\n"
        f'#define VM_DATA_DIR "{data_dir}"\n'
        "#endif\n", encoding="utf-8")

    for name in HAND_WRITTEN_TASKS:
        src = out_dir / name
        if not src.exists():
            raise FileNotFoundError(f"hand-written task body missing: {src}")
        shutil.copyfile(src, inc / name)

    comp = elaborate(VecMult, {"dwid": int(dwid), "vlen": int(vlen)}, name=TOP)
    spec = composite_top_spec(comp, width=int(dwid))
    gen = out_dir / GEN_DIR
    gen.mkdir(parents=True, exist_ok=True)
    cpp = gen / f"{spec.top_name}.cpp"
    cpp.write_text(render_top(spec), encoding="utf-8")
    (out_dir / f"{spec.top_name}.tcl").write_text(
        render_tcl(spec.top_name, part=PART, period_ns=PERIOD_NS), encoding="utf-8")
    print(f"generated {cpp.relative_to(out_dir)} + {spec.top_name}.tcl "
          f"(dwid={dwid}, vlen={vlen}, LW={lane_width(dwid)})")
    return cpp


