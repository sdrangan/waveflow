"""os_filterbank_build.py -- the filter bank's build DAG (``plans/shared_kernel.md`` Stage 5).

    python -m examples.os_filterbank.os_filterbank_build --through pysim           # pysim only
    python -m examples.os_filterbank.os_filterbank_build --through codegen         # + headers and tops
    python -m examples.os_filterbank.os_filterbank_build                           # the bank through compare
    python -m examples.os_filterbank.os_filterbank_build --through long_compare    # the long scenario
    python -m examples.os_filterbank.os_filterbank_build --through front_compare   # a front alone, at RTL
    python -m examples.os_filterbank.os_filterbank_build --through post_compare    # post alone, at RTL

The three stage bodies are hand-written (``src/``); everything else is generated: the schemas' C++ (framed,
at the widths each travels at), the FFT's configuration, wrappers and lane routines (``ssr_fft.hls``), the
stream blocks' bodies, a configuration header of the example's constants, and three free-running tops --
the bank, a front alone and post alone.  The arbiter and the demuxes have gates of their own
(``tests/streams/test_arbiter_demux.py``) and the FFT its own (``tests/dsp/ssr_fft/test_xsi.py``); ``pre``
is verified inside the bank.  Built for the RFSoC 4x2 at 250 MHz, the FFT's target.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, ClassVar

import examples.os_filterbank.os_filterbank as fb
from waveflow.build.build import BuildConfig, BuildDag, BuildStep
from waveflow.build.composite_gen import (
    GEN_DIR,
    INCLUDE_DIR,
    RFSOC4X2_PART,
    RFSOC4X2_PERIOD_NS,
    composite_top_spec,
    render_tcl,
    render_top,
    tcl_path,
)
from waveflow.build.streamutils import MemMgrStep, StreamUtilsStep
from waveflow.build.system_dag import add_system_steps
from waveflow.dsp.ssr_fft import hls as fft_hls
from waveflow.hw.arrayutils import _array_utils_filename, _array_utils_namespace
from waveflow.hw.dataschema import DataSchemaStep
from waveflow.hw.harness import harness
from waveflow.simulation.simulation import Simulation
from waveflow.streams import StreamArbiterStep, StreamDemuxStep

HERE = Path(__file__).resolve().parent
WORK_DIR = "xsi_work"
#: The system tops: the bank, a front alone, post alone.  Each wraps the csynth'd kernel of the
#: module's own name (``cpp_kernel_name``), so it must not be called the same.
TOP, FRONT_TOP, POST_TOP = "os_filterbank_top", "os_front_top", "os_post_top"
#: Bounds on the RTL runs, in cycles.
N_CYCLES = {"test": 20000, "long": 60000}
CONFIG_H = "os_filterbank_config.h"


def render_config() -> str:
    """The example's constants for the bodies, from the Python that defines them (one source)."""
    consts = {"OS_W_LOOP": fb.W_LOOP, "OS_W_ANS": fb.W_ANS, "OS_W_MSG": fb.W_MSG, "OS_NW": fb.NW,
              "OS_PW": fb.PW, "OS_BW": fb.BW, "OS_C": fb.C, "OS_CR": fb.CR}
    return "\n".join([
        "#ifndef EXAMPLES_OS_FILTERBANK_CONFIG_H",
        "#define EXAMPLES_OS_FILTERBANK_CONFIG_H",
        "// Generated by examples/os_filterbank/os_filterbank_build.py -- do not edit.",
        f'#include "{fft_hls.config_header(fb.GEO)}"',
        f'#include "{_array_utils_filename(fb.E_IN.elem)}"',
        *[f"#define {k} {v}" for k, v in consts.items()],
        "// The FFT's configuration (its edges' types and lane routines) and the input word's lane routines.",
        f"namespace os_fft = {fft_hls.config_namespace(fb.GEO)};",
        f"namespace os_cx_in = {_array_utils_namespace(fb.E_IN.elem)};",
        "#endif",
        "",
    ])


def gen_headers(root: Path = HERE) -> None:
    root = Path(root)
    # The FFT's sources: streamutils, every edge's lane routines, its configuration, wrappers and bodies.
    fft_hls.write_sources(fb.GEO, root, INCLUDE_DIR, reorder="pingpong")
    dag = BuildDag()
    dag.add(StreamUtilsStep(output_dir=INCLUDE_DIR))       # the schemas' steps need it registered
    dag.add(MemMgrStep(output_dir=INCLUDE_DIR))
    for cls, widths in fb.SCHEMAS:
        dag.add(DataSchemaStep(cls, word_bw_supported=widths, include_dir=INCLUDE_DIR, framed=True))
    dag.add(StreamArbiterStep(output_dir=INCLUDE_DIR))
    dag.add(StreamDemuxStep(output_dir=INCLUDE_DIR))
    res = dag.run(BuildConfig(root_dir=root, params={}), force=True)
    bad = [k for k, r in res.items() if not r.success]
    if bad:
        raise RuntimeError(f"header generation failed: {bad}")
    (root / INCLUDE_DIR / CONFIG_H).write_text(render_config(), encoding="utf-8")


def gen_top(mod, root: Path = HERE) -> str:
    spec = composite_top_spec(mod, width=fb.W_LOOP,
                              port_widths={n: int(ep.bitwidth) for n, ep in mod.boundary})
    gen = Path(root) / GEN_DIR
    gen.mkdir(parents=True, exist_ok=True)
    (gen / f"{spec.top_name}.cpp").write_text(render_top(spec), encoding="utf-8")
    tcl_path(root, spec.top_name).write_text(
        render_tcl(spec.top_name, part=RFSOC4X2_PART, period_ns=RFSOC4X2_PERIOD_NS,
                   solution_config=("config_rtl -reset state",)), encoding="utf-8")
    return spec.top_name


def modules() -> list:
    """The modules a top is built for, as the harness's fresh copies are."""
    return [fb.OsFilterBank(name=fb.OsFilterBank.cpp_kernel_name, sim=Simulation()),
            fb.OsFront(name=fb.OsFront.cpp_kernel_name, sim=Simulation(), ch=0),
            fb.OsPost(name=fb.OsPost.cpp_kernel_name, sim=Simulation())]


def generate(root: Path = HERE) -> list[str]:
    """Everything before csynth: the headers, and the three tops with their ``.tcl``."""
    gen_headers(root)
    return [gen_top(m, root) for m in modules()]


@dataclass(kw_only=True)
class OsCodegenStep(BuildStep):
    """``codegen``: :func:`generate`.  Never fresh; csynth decides by content."""

    description = "Generate the headers, the FFT's sources, the stream blocks' bodies and the three tops."
    params: ClassVar[dict] = {}
    produces: ClassVar[dict] = {"include": Path(INCLUDE_DIR), "gen": Path(GEN_DIR)}

    def is_fresh(self, config: BuildConfig, paths: dict[str, Path]) -> bool:
        return False

    def run(self, config: BuildConfig, **_: Any) -> dict[str, Any]:
        root = Path(config.root_dir)
        generate(root)
        return {"include": root / INCLUDE_DIR, "gen": root / GEN_DIR}


def build_dag(work_dir=WORK_DIR) -> BuildDag:
    """``codegen``; the bank's harness (no prefix) and on the long scenario (``long_``); a front's and
    post's harnesses (``front_``, ``post_``)."""
    dag = BuildDag()
    dag.add(OsCodegenStep(name="codegen"))
    for prefix, kind in (("", "test"), ("long_", "long")):
        add_system_steps(dag, harness(fb.OsFilterBank, workload=kind, n_cycles=N_CYCLES[kind]),
                         work_dir=work_dir, top=TOP, prefix=prefix)
    add_system_steps(dag, harness(fb.OsFront, workload="test"), work_dir=work_dir, top=FRONT_TOP,
                     prefix="front_")
    add_system_steps(dag, harness(fb.OsPost, workload="test"), work_dir=work_dir, top=POST_TOP,
                     prefix="post_")
    return dag


if __name__ == "__main__":
    from waveflow.build.cli import run_dag_cli

    run_dag_cli(lambda a: build_dag(), description=__doc__.splitlines()[0], default_through="compare",
                root_dir=HERE,
                extra_args=[(("--synth",), dict(choices=("build", "check"), default="build",
                             help="build: csynth a stale top; check: fail on one instead"))],
                params_from_args=lambda a: {"synth": a.synth})
