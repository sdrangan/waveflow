"""csim.py -- the worker's HLS body under Vitis C simulation, against the golden (E1's csim gate).

    python -m examples.cg_pool.csim [<build dir>] [--kind test|bad_args|bad_len|mixed]

Writes a scenario's ``s_in`` bursts (the ones pysim plays, :func:`.cg_pool.stimulus`) as text, a design file
that instantiates ``cg_worker_task`` on top-level AXI-Stream words and a testbench that pushes the words,
fires the body once a job until it stops reading, and writes what ``m_out`` holds; runs ``csim_design``;
and compares the output bursts, word for word and TLAST for TLAST, with :func:`.cg_pool.expected`.  The
body runs here as C++ (``ap_fixed`` semantics, no timing): it proves the arithmetic and the framing, not
the schedule -- RTL does that.  Build in a short directory (the Windows path limit).
"""
from __future__ import annotations

import argparse
import shutil
from pathlib import Path

import numpy as np

import examples.cg_pool.cg_pool as cp
import examples.cg_pool.cg_pool_build as cb

TOP = "cg_worker_csim"

DESIGN = """// GENERATED by examples/cg_pool/csim.py -- the worker's body on top-level AXI-Stream words.
#include "cg_worker_task.h"
void cg_worker_csim(hls::stream<streamutils::axi4s_word<CG_W> >& s_in,
                    hls::stream<streamutils::axi4s_word<CG_W> >& m_out) {
    cg_worker_task<streamutils::axi4s_word<CG_W>, streamutils::axi4s_word<CG_W> >(s_in, m_out);
}
"""

TB = """// GENERATED by examples/cg_pool/csim.py -- push s_in, fire once a job until the body stops reading.
#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>
#include "hls_stream.h"
#include "streamutils_hls.h"
#include "cg_pool_config.h"
void cg_worker_csim(hls::stream<streamutils::axi4s_word<CG_W> >& s_in,
                    hls::stream<streamutils::axi4s_word<CG_W> >& m_out);
typedef streamutils::axi4s_word<CG_W> word_t;
int main(int argc, char** argv) {
    if (argc < 3) { std::printf("usage: tb <in> <out>\\n"); return 2; }
    std::ifstream in(argv[1]);
    hls::stream<word_t> s_in("s_in"), m_out("m_out");
    std::string line;
    int nin = 0;
    while (std::getline(in, line)) {
        std::istringstream ss(line);
        unsigned long long hi, lo;
        int last;
        ss >> std::hex >> hi >> lo >> std::dec >> last;
        word_t w;
        w.data = (ap_uint<CG_W>(hi) << 64) | ap_uint<CG_W>(lo);
        w.last = last;
        w.keep = -1;
        w.strb = -1;
        s_in.write(w);
        ++nin;
    }
    int fires = 0;
    while (!s_in.empty() && fires < 100000) {
        const size_t before = s_in.size();
        cg_worker_csim(s_in, m_out);
        ++fires;
        if (s_in.size() == before) break;          // halted: it reads nothing any more
    }
    std::ofstream out(argv[2]);
    int nout = 0;
    while (!m_out.empty()) {
        word_t w = m_out.read();
        const ap_uint<64> hi = w.data >> 64, lo = w.data;
        char buf[64];
        std::snprintf(buf, sizeof buf, "%016llx %016llx %d", (unsigned long long)hi,
                      (unsigned long long)lo, (int)w.last);
        out << buf << "\\n";
        ++nout;
    }
    std::printf("CSIM in %d words, %d fires, out %d words, left %d\\n", nin, fires, nout, (int)s_in.size());
    return 0;
}
"""


def write_words(path: Path, bursts) -> None:
    lines = []
    for b in bursts:
        words = np.asarray(b.words if hasattr(b, "words") else b, dtype=np.uint64).reshape(-1, 2)
        for i, (lo, hi) in enumerate(words):
            lines.append(f"{int(hi):016x} {int(lo):016x} {int(i == len(words) - 1)}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def read_bursts(path: Path) -> list[np.ndarray]:
    out, cur = [], []
    for line in path.read_text(encoding="utf-8").splitlines():
        hi, lo, last = line.split()
        cur.append((int(lo, 16), int(hi, 16)))
        if last == "1":
            out.append(np.asarray(cur, dtype=np.uint64))
            cur = []
    if cur:
        out.append(np.asarray(cur, dtype=np.uint64))
    return out


def tcl(root: Path) -> str:
    inc = f"-I{(root / 'include').as_posix()} -I{(root / 'src').as_posix()} -std=c++14"
    return "\n".join([
        "open_project -reset csim_proj",
        f"set_top {TOP}",
        f'add_files {(root / "csim_design.cpp").as_posix()} -cflags "{inc}"',
        f'add_files -tb {(root / "csim_tb.cpp").as_posix()} -cflags "{inc}"',
        "open_solution -reset sol -flow_target vivado",
        f"set_part {cb.part()[0]}",
        f'csim_design -argv "{(root / "in.txt").as_posix()} {(root / "out.txt").as_posix()}"',
        "exit",
        "",
    ])


def prepare(root: Path, kind: str = "test") -> list[cp.JobSpec]:
    """Write everything csim needs into *root*; return the scenario's jobs."""
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    cb.gen_headers(root)
    (root / "src").mkdir(exist_ok=True)
    for name in ("cg_worker_task.h", "cg_split_task.h"):
        shutil.copy(cb.HERE / "src" / name, root / "src" / name)
    (root / "csim_design.cpp").write_text(DESIGN, encoding="utf-8")
    (root / "csim_tb.cpp").write_text(TB, encoding="utf-8")
    js = cp.jobs(kind)
    write_words(root / "in.txt", cp.stimulus(js))
    (root / "csim.tcl").write_text(tcl(root), encoding="utf-8")
    return js


def run(root: Path, kind: str = "test") -> tuple[list[np.ndarray], list[np.ndarray], str]:
    """csim on scenario *kind*: ``(got, want, log)`` -- the output bursts and the golden's."""
    from waveflow.toolchain import toolchain

    js = prepare(root, kind)
    out = Path(root) / "out.txt"
    if out.exists():
        out.unlink()
    res = toolchain.run_vitis_hls(Path(root) / "csim.tcl", work_dir=root, capture_output=True)
    log = (res.stdout or "") + (res.stderr or "")
    got = read_bursts(out) if out.exists() else []
    want = [np.asarray(w, dtype=np.uint64).reshape(-1, 2) for w in cp.expected(js)["m_out"]]
    return got, want, log


def compare(got, want) -> list[str]:
    errs = []
    if len(got) != len(want):
        errs.append(f"{len(got)} bursts, want {len(want)}")
    for i, (g, w) in enumerate(zip(got, want)):
        if g.shape != w.shape or not np.array_equal(g, w):
            errs.append(f"burst {i}: {g.shape} vs {w.shape}, {int(np.sum(g != w)) if g.shape == w.shape else '-'} "
                        "words differ")
    return errs


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("root", nargs="?", default="C:/wfb/cg_csim")
    ap.add_argument("--kind", default="test")
    a = ap.parse_args()
    got, want, log = run(Path(a.root), a.kind)
    print("\n".join(s for s in log.splitlines() if "CSIM" in s or "ERROR" in s or "error" in s)[-4000:])
    errs = compare(got, want)
    print("PASS" if not errs else "FAIL\n" + "\n".join(errs))
