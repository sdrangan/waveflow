"""cg_pool_build.py -- the B1 CG engine's build DAG (``plans/dse_matrix_sched.md`` Section 7a, E1).

    python -m examples.cg_pool.cg_pool_build --through pysim            # pysim only
    python -m examples.cg_pool.cg_pool_build --through codegen          # + headers and tops
    python -m examples.cg_pool.cg_pool_build --through worker_compare   # the worker alone, at RTL
    python -m examples.cg_pool.cg_pool_build --through split_compare    # the split alone, at RTL
    python -m examples.cg_pool.cg_pool_build --through pool2_compare    # the pool at 2 workers, at RTL
    python -m examples.cg_pool.cg_pool_build --through pool4_compare    # ... at 4

The two bodies are hand-written (``src/cg_worker_task.h``, ``src/cg_split_task.h``); everything else is
generated: the schemas' C++ (framed, 128 bits), the two complex elements' lane routines, the pool blocks'
bodies, a configuration header -- the sizes and every register and exact accumulator type, from
:mod:`.cg_golden`'s formats (one source) -- and the free-running tops.

**The part.**  ``WAVEFLOW_CG_PART=rfsoc`` builds for the RFSoC 4x2 (``xczu48dr``) at 4 ns, the E3 platform
(the lab machine); the default is ``DEFAULT_PART`` at its default clock (this repository's gates).  Build
in a short directory: csynth fails silently past the Windows path limit.
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any, ClassVar

import examples.cg_pool.cg_golden as cgg
import examples.cg_pool.cg_pool as cp
from waveflow.build.build import BuildConfig, BuildDag, BuildStep
from waveflow.build.composite_gen import (
    DEFAULT_PART,
    DEFAULT_PERIOD_NS,
    GEN_DIR,
    INCLUDE_DIR,
    RFSOC4X2_PART,
    RFSOC4X2_PERIOD_NS,
    composite_top_spec,
    render_tcl,
    render_top,
    tcl_path,
)
from waveflow.build.streamutils import MemMgrStep, StreamUtilsStep
from waveflow.build.system_dag import add_system_steps
from waveflow.hw.arrayutils import _array_utils_filename, _array_utils_namespace, gen_array_utils
from waveflow.hw.dataschema import DataSchemaStep
from waveflow.hw.harness import harness
from waveflow.linalg.cg import accumulator_formats
from waveflow.linalg.formats import ap_type
from waveflow.simulation.simulation import Simulation
from waveflow.streams import StreamArbiterStep, StreamDispatchStep
from waveflow.utils import fixputils as fx

HERE = Path(__file__).resolve().parent
WORK_DIR = "xsi_work"
CONFIG_H = "cg_pool_config.h"
#: The system tops (each wraps the csynth'd kernel of the module's own name, so not called the same).
WORKER_TOP, SPLIT_TOP = "cg_worker_top", "cg_split_top"
POOL_SIZES = (2, 4)


def build_root() -> Path:
    """Where the build runs: ``WAVEFLOW_CG_ROOT`` (a short directory -- csynth fails silently past the
    Windows path limit; the bodies in ``src/`` are copied there), else this folder."""
    import shutil

    env = os.environ.get("WAVEFLOW_CG_ROOT")
    if not env:
        return HERE
    root = Path(env)
    (root / "src").mkdir(parents=True, exist_ok=True)
    for f in (HERE / "src").glob("*.h"):
        shutil.copy(f, root / "src" / f.name)
    return root


def pool_top(n: int) -> str:
    return f"cg_pool{n}_top"


def part() -> tuple[str, float]:
    """The part and clock period the tops are built for."""
    if os.environ.get("WAVEFLOW_CG_PART", "").lower() == "rfsoc":
        return RFSOC4X2_PART, RFSOC4X2_PERIOD_NS
    return DEFAULT_PART, DEFAULT_PERIOD_NS


def types() -> dict[str, str]:
    """Every C++ type the worker's body computes in: the registers, and the exact accumulators."""
    f = cgg.FORMATS
    g = f.cg
    acc = accumulator_formats(g, cgg.N_RX)
    regs = {"h_t": f.H, "p_t": g.P, "r_t": g.R, "x_t": g.X, "s_t": g.S, "t_t": f.T, "xo_t": f.Xo,
            "ps_t": g.ps, "rz_t": g.rz, "alpha_t": g.alpha, "beta_t": g.beta, "rzw_t": acc["rzw"],
            "acc_t_t": f.acc_T(), "acc_u_t": f.acc_U(), "dot_ps_t": acc["dot_ps"],
            "dot_rz_t": acc["dot_rz"]}
    return {k: ap_type(v) for k, v in regs.items()}


def render_config() -> str:
    """The example's constants and types for the bodies, from the Python that defines them."""
    consts = {"CG_W": cp.W, "CG_NRX": cgg.N_RX, "CG_MMAX": cgg.M_MAX, "CG_CMAX": cgg.C_MAX,
              "CG_TMAX": cgg.T_MAX, "CG_COLW": cp.COL_WORDS, "CG_LANES": cp.LANES,
              # the stop floor, a stored integer of rz's format, as its exact value (a power-of-two scale)
              "CG_RZ_FLOOR_VAL": repr(float(fx.to_float(cgg.FORMATS.rz_floor, cgg.FORMATS.cg.rz)))}
    assert cp.P_MAC == 4 * cp.LANES and cp.V_LANES == cp.LANES      # the body's banking (src/)
    return "\n".join([
        "#ifndef EXAMPLES_CG_POOL_CONFIG_H",
        "#define EXAMPLES_CG_POOL_CONFIG_H",
        "// Generated by examples/cg_pool/cg_pool_build.py -- do not edit.",
        "#include <ap_fixed.h>",
        f'#include "{_array_utils_filename(cp.E_H.elem)}"',
        f'#include "{_array_utils_filename(cp.E_X.elem)}"',
        *[f"#define {k} {v}" for k, v in consts.items()],
        "namespace cg_cfg {",
        *[f"typedef {v} {k};" for k, v in types().items()],
        "}  // namespace cg_cfg",
        "// The lane routines of H and B (s_in) and of X (m_out).",
        f"namespace cg_h = {_array_utils_namespace(cp.E_H.elem)};",
        f"namespace cg_x = {_array_utils_namespace(cp.E_X.elem)};",
        "#endif",
        "",
    ])


def gen_headers(root: Path = HERE) -> None:
    root = Path(root)
    dag = BuildDag()
    dag.add(StreamUtilsStep(output_dir=INCLUDE_DIR))       # the schemas' steps need it registered
    dag.add(MemMgrStep(output_dir=INCLUDE_DIR))
    for cls, widths in cp.SCHEMAS:
        dag.add(DataSchemaStep(cls, word_bw_supported=widths, include_dir=INCLUDE_DIR, framed=True))
    dag.add(StreamArbiterStep(output_dir=INCLUDE_DIR))
    dag.add(StreamDispatchStep(output_dir=INCLUDE_DIR))
    res = dag.run(BuildConfig(root_dir=root, params={}), force=True)
    bad = [k for k, r in res.items() if not r.success]
    if bad:
        raise RuntimeError(f"header generation failed: {bad}")
    for e in (cp.E_H, cp.E_X):                              # the lane routines, beside the rest
        gen_array_utils(e.elem, [cp.W], cfg=BuildConfig(root_dir=root / INCLUDE_DIR))
    (root / INCLUDE_DIR / CONFIG_H).write_text(render_config(), encoding="utf-8")


def gen_top(mod, root: Path = HERE) -> str:
    spec = composite_top_spec(mod, width=cp.W)
    gen = Path(root) / GEN_DIR
    gen.mkdir(parents=True, exist_ok=True)
    (gen / f"{spec.top_name}.cpp").write_text(render_top(spec), encoding="utf-8")
    p, period = part()
    tcl_path(root, spec.top_name).write_text(
        render_tcl(spec.top_name, part=p, period_ns=period, solution_config=("config_rtl -reset state",)),
        encoding="utf-8")
    return spec.top_name


def clock_hz() -> float:
    return 1e9 / part()[1]


def modules() -> list:
    """The modules a top is built for, as the harness's fresh copies are."""
    from waveflow.hw.clock import Clock
    from waveflow.hw.hw_module import kernel_name

    clk = Clock(freq=clock_hz())
    out = [cp.CgWorker(name=cp.CgWorker.cpp_kernel_name, sim=Simulation(), clk=clk),
           cp.CgSplit(name=cp.CgSplit.cpp_kernel_name, sim=Simulation(), clk=clk)]
    for n in POOL_SIZES:
        name = kernel_name(cp.CgPool, {"n_workers": n})
        out.append(cp.CgPool(name=name, sim=Simulation(), n_workers=n, clk=clk))
    return out


def generate(root: Path = HERE) -> list[str]:
    """Everything before csynth: the headers, and the tops with their ``.tcl``."""
    gen_headers(root)
    return [gen_top(m, root) for m in modules()]


@dataclass(kw_only=True)
class CgCodegenStep(BuildStep):
    """``codegen``: :func:`generate`.  Never fresh; csynth decides by content."""

    description = "Generate the headers, the pool blocks' bodies, the configuration and the tops."
    params: ClassVar[dict] = {}
    produces: ClassVar[dict] = {"include": Path(INCLUDE_DIR), "gen": Path(GEN_DIR)}

    def is_fresh(self, config: BuildConfig, paths: dict[str, Path]) -> bool:
        return False

    def run(self, config: BuildConfig, **_: Any) -> dict[str, Any]:
        root = Path(config.root_dir)
        generate(root)
        return {"include": root / INCLUDE_DIR, "gen": root / GEN_DIR}


#: Bounds on the RTL runs, in cycles (each scenario's pysim end, with room).
N_CYCLES = {"worker": 40000, "split": 4000, "pool": 120000}


def build_dag(work_dir=WORK_DIR) -> BuildDag:
    """``codegen``; the worker's harness (``worker_``), the split's (``split_``), and the pool at each size
    on the mixed batch (``pool<n>_``)."""
    from waveflow.hw.clock import Clock

    clk = Clock(freq=clock_hz())
    dag = BuildDag()
    dag.add(CgCodegenStep(name="codegen"))
    add_system_steps(dag, harness(cp.CgWorker(name="w", sim=Simulation(), clk=clk), workload="test",
                                  n_cycles=N_CYCLES["worker"]),
                     work_dir=work_dir, top=WORKER_TOP, prefix="worker_")
    add_system_steps(dag, harness(cp.CgSplit(name="s", sim=Simulation(), clk=clk), workload="test",
                                  n_cycles=N_CYCLES["split"]),
                     work_dir=work_dir, top=SPLIT_TOP, prefix="split_")
    for n in POOL_SIZES:
        mod = cp.CgPool(name="p", sim=Simulation(), n_workers=n, clk=clk)
        add_system_steps(dag, harness(mod, workload="mixed", n_cycles=N_CYCLES["pool"]),
                         work_dir=work_dir, top=pool_top(n), prefix=f"pool{n}_")
    return dag


if __name__ == "__main__":
    from waveflow.build.cli import run_dag_cli

    run_dag_cli(lambda a: build_dag(), description=__doc__.splitlines()[0], default_through="pysim",
                root_dir=build_root(),
                extra_args=[(("--synth",), dict(choices=("build", "check"), default="build",
                             help="build: csynth a stale top; check: fail on one instead"))],
                params_from_args=lambda a: {"synth": a.synth})
