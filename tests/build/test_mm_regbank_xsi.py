"""Stage 2 of ``plans/mm_slave_adaptor.md`` — the register bank, under XSI, beside two queue windows.

One host reaches three views through AMD's crossbar -- the shape a kernel like ``mm_fir`` needs:

* MI0 = ``mm_regbank`` (0x0000): 4 config words behind shadow-and-commit -> ``k_cfg`` packets; a
  2-word status bank fed by ``k_stat``.
* MI1 = ``mm_queue_in``  (0x1000) -> ``k_in``.
* MI2 = ``mm_queue_out`` (0x2000) <- ``k_out``.

What it checks, beyond Stage 1: **snapshot isolation** (a shadow write after a commit does not reach
the packet that commit sent), **commits are never merged or dropped** (with the config sink held off,
the second commit stalls the bus until the first packet has gone, then goes out with its own
contents), the commit counter, and that a status read returns the most recent COMPLETE message.

Run: ``pytest tests/build/test_mm_regbank_xsi.py -m xsi`` (needs Vivado).
"""
from __future__ import annotations

from pathlib import Path

import pytest

from waveflow.build.axi_xbar import (
    AxiXbarConfig,
    AxiXbarRange,
    axi_port_decls,
    axi_signals,
    axi_wire_decls,
    generate_axi_xbar,
    render_xbar_instance,
)
from waveflow.build.mm_adaptor_gen import (
    QueueView,
    RegBankView,
    axis_port_decls,
    leaf_sources,
    mi_wire_signals,
    render_view_slot,
)
from waveflow.build.xsi_workspace import XsiWorkspace
from waveflow.toolchain.toolchain import find_vivado_path

WORK = Path(__file__).resolve().parent / "_xsi_work"
CFG_FROM = 100

XBAR = AxiXbarConfig(
    name="xbar_mm3_1x3", n_si=1,
    mi=[AxiXbarRange(0x0000, 12), AxiXbarRange(0x1000, 12), AxiXbarRange(0x2000, 12)],
    data_width=64, addr_width=32, id_width=1,
)
VIEWS = [RegBankView("regs", ncfg=4, nstat=2, cfg_axis="k_cfg", status_axis="k_stat"),
         QueueView("qin", "in", axis="k_in", depth=64),
         QueueView("qout", "out", axis="k_out", depth=64)]


def render_top(top: str) -> str:
    dw, aw, idw = XBAR.data_width, XBAR.addr_width, XBAR.id_width
    ports = ["input wire ap_clk", "input wire ap_rst_n"]
    ports += axi_port_decls("s0_axi", axi_signals(dw, aw, idw), facing="slave")
    ports += axis_port_decls("k_cfg", dw, kernel_reads=True)
    ports += axis_port_decls("k_stat", dw, kernel_reads=False)
    ports += axis_port_decls("k_in", dw, kernel_reads=True)
    ports += axis_port_decls("k_out", dw, kernel_reads=False)
    mi = [f"mi{k}_axi" for k in range(len(VIEWS))]
    body = []
    for p in mi:
        body += ["  " + d for d in axi_wire_decls(p, mi_wire_signals(dw, aw, idw))]
    body.append(render_xbar_instance(XBAR, "u_xbar", ["s0_axi"], mi))
    for view, p in zip(VIEWS, mi):
        body.append(render_view_slot(view, p, dw, aw, idw))
    return (f"// {top}.v -- GENERATED by tests/build/test_mm_regbank_xsi.py (Stage 2 gate).\n"
            f"`timescale 1ns/1ps\nmodule {top} (\n  " + ",\n  ".join(ports) + "\n);\n"
            + "\n".join(body) + "endmodule\n")


TB = r'''// mm3_tb.cpp -- Stage 2 gate: register bank + queues behind one crossbar.
#include "xsi_bfm.h"
using namespace wfbfm;

int main() {
    XsiSim sim("__DLL__", "mm3.wdb");
    const uint64_t REGS = 0x0000, COMMIT = 0x0800, STATUS = 0x0C00, QIN = 0x1000, QOUT = 0x2000;
    AxiMmMaster host(sim.dut(), "s0_axi", 8, 0);
    AxisSlave  cfg(sim.dut(), "k_cfg");
    AxisMaster stat(sim.dut(), "k_stat", {0x51, 0x52, 0x61, 0x62});   // two 2-word messages
    AxisSlave  kin(sim.dut(), "k_in");
    AxisMaster kout(sim.dut(), "k_out", {0x71, 0x72, 0x73});
    cfg.ready_from = __CFG_FROM__;
    std::vector<XsiSimObj*> all = {&host, &cfg, &stat, &kin, &kout};
    auto drive = [&] { for (auto* p : all) p->drive(); };

    size_t w0 = host.write(REGS, {0xC0, 0xC1, 0xC2, 0xC3});
    size_t c1 = host.write(COMMIT, {1});
    size_t w1 = host.write(REGS + 8, {0xAA});          // after commit 1: must NOT reach packet 1
    size_t c2 = host.write(COMMIT, {1});                // stalls: packet 1 is still waiting for k_cfg
    size_t rs = host.read(REGS, 4);
    size_t rc = host.read(COMMIT, 1);
    size_t st = host.read(STATUS, 2);
    size_t qi = host.write(QIN, {2, 0xD0, 0xD1});
    size_t qo = host.read(QOUT, 3);

    sim.reset(drive);
    long cyc = 0;
    for (; cyc < 2000 && !(host.idle() && cfg.count() >= 8 && kin.count() >= 2); ++cyc) {
        sim.clock_low();  for (auto* p : all) p->sample();
        sim.clock_high(); for (auto* p : all) p->update(); drive();
    }

    int fail = 0;
    auto check = [&](const char* what, bool ok) { if (!ok) { std::printf("FAIL %s\n", what); ++fail; } };
    check("host idle", host.idle());
    check("cfg packets", cfg.words() == std::vector<uint64_t>({0xC0, 0xC1, 0xC2, 0xC3, 0xC0, 0xAA, 0xC2, 0xC3}));
    check("cfg TLAST", cfg.bounds() == std::vector<uint64_t>({4, 8}));
    check("shadow readback", host.op(rs).rdata == std::vector<uint64_t>({0xC0, 0xAA, 0xC2, 0xC3}));
    check("commit count", host.op(rc).rdata == std::vector<uint64_t>({2}));
    check("latest status", host.op(st).rdata == std::vector<uint64_t>({0x61, 0x62}));
    check("queue in", kin.words() == std::vector<uint64_t>({0xD0, 0xD1}));
    check("queue out", host.op(qo).rdata == std::vector<uint64_t>({0x71, 0x72, 0x73}));
    for (size_t i = 0; i < host.nops(); ++i) check("resp OKAY", host.op(i).resp == 0);

    const char* names[] = {"w0", "c1", "w1", "c2", "rs", "rc", "st", "qi", "qo"};
    std::printf("LAT");
    for (size_t i = 0; i < host.nops(); ++i)
        std::printf(" %s=%ld", names[i], host.op(i).t_end - host.op(i).t_start + 1);
    std::printf("\nCFG p1=%ld p2=%ld\n", cfg.cycle_of_word(4), cfg.cycle_of_word(8));
    std::printf(fail ? "FAILED test (%d)\n" : "PASSED test\n", fail);
    sim.close();
    return fail ? 1 : 0;
}
'''


def _parse(out: str, tag: str) -> dict[str, int]:
    line = next(ln for ln in out.splitlines() if ln.startswith(tag + " "))
    return {k: int(v) for k, v in (kv.split("=") for kv in line.split()[1:])}


@pytest.fixture(scope="module")
def mm3_run() -> str:
    if not find_vivado_path():
        pytest.skip("XSI gate prerequisite missing: Vivado (create_ip + xsim)")
    ip = generate_axi_xbar(XBAR, WORK / "ip")
    ws = XsiWorkspace(WORK / "mm3", top="mm3_top")
    tb = TB.replace("__DLL__", ws.design_dll).replace("__CFG_FROM__", str(CFG_FROM))
    ws.prepare(rtl_files=ip.sim_files + leaf_sources() + ["mm3_top.v"],
               include_dirs=ip.include_dirs, tb_name="mm3_tb", tb_cpp=tb,
               extra_files={"mm3_top.v": render_top("mm3_top")})
    return ws.run()


@pytest.mark.xsi
def test_regbank_functional(mm3_run: str):
    assert "PASSED test" in mm3_run, mm3_run[-3000:]


@pytest.mark.xsi
def test_regbank_cycles(mm3_run: str):
    lat, cfg = _parse(mm3_run, "LAT"), _parse(mm3_run, "CFG")
    print(lat, cfg)
    assert lat == EXPECTED_LAT, f"latency moved: {lat}"
    assert cfg == EXPECTED_CFG, f"config packet timing moved: {cfg}"


#: Recorded 2026-10-02.  Every op costs the Stage 1 fixed 4-5 cycles plus one per beat, except c2:
#: commit 2 arrives while packet 1 is still waiting for the held-off config sink (CFG_FROM = 100), so
#: its write stalls the bus for 87 cycles -- the commit is held, never merged or dropped.
EXPECTED_LAT: dict[str, int] = {"w0": 9, "c1": 5, "w1": 5, "c2": 87, "rs": 9, "rc": 5, "st": 6,
                                "qi": 8, "qo": 8}
#: Last word of each config packet: packet 1 drains 101..104 once the sink opens; commit 2 is then
#: accepted and packet 2 drains by 109.
EXPECTED_CFG: dict[str, int] = {"p1": 104, "p2": 109}
