WORK = Path(__file__).resolve().parent / "_xsi_work"
DW, AW, IDW = 64, 32, 1
BAW = 8                     # 256 words: the 4 KB window's upper half is outside the memory
NW = 1 << BAW
#: Words per cycle a lone read streams at, by leaf: one a cycle, or one every LAT + 1 = 2.
CYCLES_PER_WORD = {"mm_bram_port_pipe": 1, "mm_bram_port": 2}


def _port_b_idle(dw: int) -> list[str]:
    """Port B of the memory held idle: nothing but the bus touches it here."""
    return ["  wire [31:0] kb_addr = 32'd0; wire kb_en = 1'b0; wire [1:0] kb_we = 2'b00;",
            f"  wire [{dw - 1}:0] kb_din = {{{dw}{{1'b0}}}}; wire [{dw - 1}:0] kb_dout;"]


def render_alone_top(top: str, leaf: str) -> str:
    view = BRAM_VIEWS[leaf]("win", kport="kb", baw=BAW)
    ports = ["input wire ap_clk", "input wire ap_rst_n"]
    ports += axi_port_decls("s0_axi", axi_signals(DW, AW, IDW), facing="slave")
    body = _port_b_idle(DW) + [render_view_slot(view, "s0_axi", DW, AW, IDW)]
    return (f"// {top}.v -- GENERATED by tests/build/test_mm_bram_pipe_xsi.py (the leaf alone, {leaf}).\n"
            f"`timescale 1ns/1ps\nmodule {top} (\n  " + ",\n  ".join(ports) + "\n);\n"
            + "\n".join(body) + "endmodule\n")


ALONE_TB = r'''// bram_alone_tb.cpp -- one BRAM window behind its front, every word checked (bram_fullrate_port.md).
#include <algorithm>
#include <string>
#include "xsi_bfm.h"
using namespace wfbfm;

static const long NW = __NW__;          // words in the memory; the 4 KB window holds 2 * NW
static const uint64_t BPW = 8;

static std::vector<uint64_t> vals(uint64_t base, int n) {
    std::vector<uint64_t> v; for (int i = 0; i < n; ++i) v.push_back(base + 0x11 * (uint64_t)i); return v;
}

int main() {
    XsiSim sim("__DLL__", "alone.wdb");
    AxiMmMaster host(sim.dut(), "s0_axi", (int)BPW, 0, true);   // overlap_rw: an AW and an AR at once
    std::vector<XsiSimObj*> all = {&host};
    auto drive = [&] { for (auto* p : all) p->drive(); };

    // The model: what the memory holds, updated as each write is queued (phases never overlap a read
    // and a write of the same words).
    std::vector<uint64_t> mem(NW);
    for (long i = 0; i < NW; ++i) mem[i] = 0x5A00000000000000ull | ((uint64_t)i << 16) | (uint64_t)(7 * i + 1);
    struct Want { size_t op; std::vector<uint64_t> data; uint32_t resp; std::string what; };
    std::vector<Want> wants;
    auto rd = [&](const std::string& what, long w, uint32_t n, long nb, int burst = -1) {
        size_t i = host.read((uint64_t)w * BPW, n, nb);
        host.op_mut(i).burst = burst;
        Want x{i, {}, 0, what};
        for (uint32_t k = 0; k < n; ++k) {
            long a = (burst == 0) ? w : w + (long)k;
            if (a < NW) x.data.push_back(mem[a]); else { x.data.push_back(0); x.resp = 2; }
        }
        wants.push_back(x);
        return i;
    };
    auto wr = [&](long w, std::vector<uint64_t> d, long nb, int burst = -1) {
        size_t i = host.write((uint64_t)w * BPW, d, nb);
        host.op_mut(i).burst = burst;
        for (size_t k = 0; k < d.size(); ++k) {
            long a = (burst == 0) ? w : w + (long)k;
            if (a < NW) mem[a] = d[k];
        }
        return i;
    };

    const uint32_t lone_n[] = {1, 2, 16, 64, 256};
    std::vector<size_t> lone, back, stall, mix, fixed, oob;
    size_t sweep = 0, mixback = 0;
    // One phase at a time, each queued when the previous one has finished.
    auto queue = [&](int ph, long now) -> bool {
        switch (ph) {
        case 0: wr(0, mem, now + 2); return true;                                 // fill
        case 1: for (int k = 0; k < 5; ++k)                                        // each read alone
                    lone.push_back(rd("lone", lone_n[k] == 256 ? 0 : 17, lone_n[k], now + 10 + 800L * k));
                return true;
        case 2: for (int k = 0; k < 4; ++k) back.push_back(rd("back16", 16 * k, 16, now + 10));
                back.push_back(rd("back64", 64, 64, now + 10));
                back.push_back(rd("back64", 128, 64, now + 10));
                return true;
        case 3: host.stall_pct = 50; host.stall_seed = 7;                          // RREADY at random
                stall.push_back(rd("stall64", 100, 64, now + 10));
                stall.push_back(rd("stall256", 0, 256, now + 10));
                return true;
        case 4: host.stall_pct = 0;                                                // AW / AR alternation
                for (int k = 0; k < 8; ++k) {
                    mix.push_back(wr(NW / 2 + 16 * k, vals(0xC000 + 0x100 * k, 16), now + 10));
                    mix.push_back(rd("mix", 16 * k, 16, now + 10));
                }
                return true;
        case 5: mixback = rd("mix_back", NW / 2, (uint32_t)(NW / 2), now + 10); return true;
        case 6: fixed.push_back(rd("fixed_rd", 5, 8, now + 10, 0));               // FIXED: one word
                fixed.push_back(wr(7, vals(0xF1F0, 4), now + 10, 0));            // the last beat wins
                return true;
        case 7: fixed.push_back(rd("fixed_back", 6, 3, now + 10)); return true;
        case 8: oob.push_back(rd("oob_edge", NW - 2, 4, now + 10));               // 2 in, 2 outside
                oob.push_back(rd("oob_all", NW + 44, 16, now + 10));
                oob.push_back(wr(NW + 144, vals(0xDEAD, 2), now + 10));          // dropped
                return true;
        case 9: oob.push_back(rd("oob_wr", NW + 144, 2, now + 10));
                oob.push_back(rd("no_alias", 144, 2, now + 10));                   // not overwritten
                return true;
        case 10: host.stall_pct = 30; host.stall_seed = 11;
                 sweep = rd("sweep", 0, (uint32_t)NW, now + 10);
                 return true;
        default: return false;
        }
    };

    sim.reset(drive);
    int phase = 0;
    long cyc = 0;
    for (; cyc < 40000; ++cyc) {
        if (host.idle() && !queue(phase++, host.cycle())) break;
        sim.clock_low();  for (auto* p : all) p->sample();
        sim.clock_high(); for (auto* p : all) p->update(); drive();
    }

    int fail = 0;
    auto check = [&](const std::string& what, bool ok) { if (!ok) { std::printf("FAIL %s\n", what.c_str()); ++fail; } };
    check("every phase ran", phase == 12 && host.idle());
    size_t words = 0;
    for (const auto& w : wants) {
        const auto& o = host.op(w.op);
        check(w.what + " data", o.rdata == w.data);
        check(w.what + " resp", o.resp == w.resp);
        words += w.data.size();
    }
    for (size_t i = 0; i < host.nops(); ++i)
        if (host.op(i).write) check("write OKAY", host.op(i).resp == 0);
    auto dur = [&](size_t i) { return host.op(i).t_end - host.op(i).t_start + 1; };
    std::printf("CHECKED reads=%zu words=%zu\n", wants.size(), words);
    std::printf("LONE");
    for (int k = 0; k < 5; ++k) std::printf(" n%u=%ld", lone_n[k], dur(lone[k]));
    std::printf("\nBACK");
    for (size_t k = 0; k < back.size(); ++k) std::printf(" e%zu=%ld", k, host.op(back[k]).t_end - host.op(back[0]).t_start + 1);
    std::printf("\nSTALL d64=%ld d256=%ld sweep=%ld\n", dur(stall[0]), dur(stall[1]), dur(sweep));
    // The order the queued writes and reads finished in: the front alternates AW and AR.
    std::vector<size_t> by_end(mix);
    std::sort(by_end.begin(), by_end.end(), [&](size_t a, size_t b) { return host.op(a).t_end < host.op(b).t_end; });
    std::string order;
    for (size_t i : by_end) order += host.op(i).write ? "W" : "R";
    std::printf("MIX span=%ld back=%ld order=%s\n",
                host.op(by_end.back()).t_end - host.op(mix[0]).t_start + 1, dur(mixback), order.c_str());
    std::printf("EDGE fixed_rd=%ld fixed_wr=%ld oob_edge=%ld oob_all=%ld\n", dur(fixed[0]), dur(fixed[1]),
                dur(oob[0]), dur(oob[1]));
    std::printf(fail ? "FAILED test (%d)\n" : "PASSED test\n", fail);
    sim.close();
    return fail ? 1 : 0;
}
'''


def render_order_top(top: str) -> str:
    ports = ["input wire ap_clk", "input wire ap_rst_n"]
    ports += axi_port_decls("s0_axi", axi_signals(DW, AW, IDW), facing="slave")
    ports += axis_port_decls("k_out", DW, kernel_reads=False)
    ports += axis_port_decls("k_in", DW, kernel_reads=True)
    body = _port_b_idle(DW) + [render_adaptor_slot("ad", ORDER_VIEWS, "s0_axi", DW, AW, IDW)]
    return (f"// {top}.v -- GENERATED by tests/build/test_mm_bram_pipe_xsi.py (order across leaves).\n"
            f"`timescale 1ns/1ps\nmodule {top} (\n  " + ",\n  ".join(ports) + "\n);\n"
            + "\n".join(body) + "endmodule\n")


#: View 0 at 0x0000, 1 at 0x1000, 2 at 0x2000; the span is 4 windows, so 0x3000 is the hole.
ORDER_VIEWS = [QueueView("qo", "out", axis="k_out", depth=64),
               BramViewPipe("win", kport="kb", baw=BAW),
               QueueView("qi", "in", axis="k_in", depth=16)]

ORDER_TB = r'''// bram_order_leaves_tb.cpp -- a queue, the pipelined window and a hole behind one front.
#include <algorithm>
#include <string>
#include "xsi_bfm.h"
using namespace wfbfm;

static const long NW = __NW__;
static const uint64_t BPW = 8;
static const uint64_t QO = 0x0000, QO_READY = 0x0800, WIN = 0x1000, HOLE = 0x3000;
static const uint64_t QI_DEPTH = 16;

int main() {
    XsiSim sim("__DLL__", "order.wdb");
    AxiMmMaster host(sim.dut(), "s0_axi", (int)BPW, 0);
    std::vector<uint64_t> g;
    for (int i = 0; i < 64; ++i) g.push_back(0x0E00000000000000ull + 3 * (uint64_t)i + 1);
    AxisMaster src(sim.dut(), "k_out", g);      // the kernel's words, popped through queue out
    AxisSlave sink(sim.dut(), "k_in");          // queue in: nothing is written to it
    std::vector<XsiSimObj*> all = {&host, &src, &sink};
    auto drive = [&] { for (auto* p : all) p->drive(); };

    std::vector<uint64_t> mem(NW);
    for (long i = 0; i < NW; ++i) mem[i] = 0x3C00000000000000ull | ((uint64_t)i << 20) | (uint64_t)(5 * i + 2);
    struct Want { size_t op; std::vector<uint64_t> data; uint32_t resp; std::string what; };
    std::vector<Want> wants;
    size_t popped = 0;
    auto raw = [&](const std::string& what, uint64_t addr, std::vector<uint64_t> data, uint32_t resp,
                   long nb) {
        size_t i = host.read(addr, (uint32_t)data.size(), nb);
        wants.push_back({i, data, resp, what});
    };
    auto pop = [&](uint32_t n, long nb) {
        raw("pop", QO, std::vector<uint64_t>(g.begin() + popped, g.begin() + popped + n), 0, nb);
        popped += n;
    };
    auto win = [&](long w, uint32_t n, long nb) {
        raw("win", WIN + (uint64_t)w * BPW, std::vector<uint64_t>(mem.begin() + w, mem.begin() + w + n), 0, nb);
    };
    auto crossings = [&](const std::string& tag, long nb) {
        const uint64_t ready = g.size() - popped;          // words still in queue out
        raw(tag + "_qo_win", 0x0FF0, {ready, ready, mem[0], mem[1]}, 0, nb);
        raw(tag + "_win_qi", 0x1FF0, {0, 0, QI_DEPTH, QI_DEPTH}, 2, nb);   // outside the memory, then vacancy
        raw(tag + "_qi_hole", 0x2FF0, {QI_DEPTH, QI_DEPTH, 0, 0}, 2, nb);
    };
    long t_alt0 = 0, t_hole0 = 0;
    size_t alt_first = 0, alt_last = 0, hole_first = 0;
    auto queue = [&](int ph, long now) -> bool {
        switch (ph) {
        case 0: host.write(WIN, mem, now + 2); return true;                       // fill the window
        case 1: host.stall_pct = 40; host.stall_seed = 3; t_alt0 = now;           // queue, window, ...
                alt_first = host.nops();
                pop(8, now + 10); win(0, 8, now + 10); pop(8, now + 10); win(40, 16, now + 10);
                pop(16, now + 10); win(100, 32, now + 10); pop(1, now + 10); win(255, 1, now + 10);
                pop(4, now + 10); win(192, 64, now + 10);
                alt_last = host.nops() - 1;
                return true;
        case 2: host.stall_pct = 60; host.stall_seed = 5; t_hole0 = now; hole_first = host.nops();
                raw("hole16", HOLE, std::vector<uint64_t>(16, 0), 2, now + 10);
                raw("hole1", HOLE + 0x800, {0}, 2, now + 10);
                return true;
        case 3: host.stall_pct = 0; crossings("x", now + 10); return true;
        case 4: host.stall_pct = 50; host.stall_seed = 9; crossings("xs", now + 10); return true;
        case 5: host.stall_pct = 0;
                raw("ready", QO_READY, {g.size() - popped}, 0, now + 10);
                pop((uint32_t)(g.size() - popped), now + 10);
                return true;
        default: return false;
        }
    };

    sim.reset(drive);
    int phase = 0;
    long cyc = 0;
    for (; cyc < 20000; ++cyc) {
        if (host.idle() && !queue(phase++, host.cycle())) break;
        sim.clock_low();  for (auto* p : all) p->sample();
        sim.clock_high(); for (auto* p : all) p->update(); drive();
    }

    int fail = 0;
    auto check = [&](const std::string& what, bool ok) { if (!ok) { std::printf("FAIL %s\n", what.c_str()); ++fail; } };
    check("every phase ran", phase == 7 && host.idle());
    check("every word popped", popped == g.size());
    check("nothing reached queue in", sink.count() == 0);
    size_t words = 0;
    for (const auto& w : wants) {
        const auto& o = host.op(w.op);
        check(w.what + " data", o.rdata == w.data);
        check(w.what + " resp", o.resp == w.resp);
        words += w.data.size();
    }
    std::printf("CHECKED reads=%zu words=%zu\n", wants.size(), words);
    std::printf("SPAN alt=%ld hole=%ld end=%ld\n", host.op(alt_last).t_end - t_alt0,
                host.op(hole_first + 1).t_end - t_hole0, host.cycle());
    std::printf(fail ? "FAILED test (%d)\n" : "PASSED test\n", fail);
    sim.close();
    return fail ? 1 : 0;
}
'''


def _parse(out: str, tag: str) -> dict[str, str]:
    line = next(ln for ln in out.splitlines() if ln.startswith(tag + " "))
    return dict(kv.split("=") for kv in line.split()[1:])


def _ints(out: str, tag: str) -> dict[str, int]:
    return {k: int(v) for k, v in _parse(out, tag).items()}


