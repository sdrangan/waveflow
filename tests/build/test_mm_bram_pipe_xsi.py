"""The full-rate BRAM window under XSI (``plans/bram_fullrate_port.md``, Stage 2).

Two gates, each its own top with the AXI port straight on the slot (no crossbar: what is measured is
the front and the leaf), driven by the C++ ``AxiMmMaster``:

* **The leaf alone** -- one BRAM window behind its front: the memory filled, then reads of 1, 2, 16, 64
  and 256 beats each alone, back-to-back bursts, RREADY held low at random, writes and reads queued
  together (the front's AW/AR alternation, the master's ``overlap_rw``), FIXED bursts, reads outside
  the memory (SLVERR, data 0) and a write there that must not alias, and a last sweep of the whole
  memory under stalls.  Every word read is checked against a model of the memory.  Run for
  ``mm_bram_port_pipe`` and, as the control that shows the testbench can tell them apart, for
  ``mm_bram_port``: a lone N-beat read takes exactly ``init + N`` cycles on the first and
  ``init + 2N`` on the second.
* **Order across leaves** -- a queue out, the pipelined window and a queue in behind ONE front (so
  ``RD_OUTST = 2`` and the decoder's order FIFO), plus the span's unused fourth window (the hole):
  reads alternating between the queue and the window under RREADY stalls, reads of the hole with
  several outstanding, and bursts that run across a window boundary into the next view -- illegal on a
  real bus (an AXI burst may not cross 4 KB), driven here because it is the one way to have reads
  outstanding at two leaves at once.  Every response must come from the leaf that owes it, in order.

Run: ``pytest tests/build/test_mm_bram_pipe_xsi.py -m xsi`` (needs Vivado's xsim).
"""
