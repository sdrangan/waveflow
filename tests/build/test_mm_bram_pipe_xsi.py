@pytest.mark.xsi
def test_leaf_alone_cycles(alone_run):
    """A lone N-beat read takes exactly ``init + N`` cycles (``init + 2N`` at ``mm_bram_port``), from
    the address phase presented to the RLAST beat, inclusive; every other phase is pinned."""
    leaf, out = alone_run
    lone = _ints(out, "LONE")
    per = CYCLES_PER_WORD[leaf]
    init = {k: v - per * int(k[1:]) for k, v in lone.items()}
    print(leaf, lone, init, _parse(out, "BACK"), _parse(out, "STALL"), _parse(out, "MIX"),
          _parse(out, "EDGE"))
    assert len(set(init.values())) == 1, f"{leaf}: the lone reads' cost is not init + {per}N: {lone}"
    assert init["n1"] == EXPECTED_INIT[leaf], f"{leaf}: init moved: {init}"
    mix = _parse(out, "MIX")
    assert mix["order"] == "WR" * 8, f"{leaf}: the front did not alternate AW and AR: {mix}"
    got = {"BACK": _ints(out, "BACK"), "STALL": _ints(out, "STALL"),
           "MIX": {k: int(v) for k, v in mix.items() if k != "order"}, "EDGE": _ints(out, "EDGE")}
    assert got == EXPECTED_ALONE[leaf], f"{leaf}: moved: {got}"


