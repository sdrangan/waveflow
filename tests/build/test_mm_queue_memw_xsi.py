"""Stage 1 witness of ``plans/mm_slave_adaptor.md`` at RTL: Producer -> MemWStream -> crossbar -> queue.

The synthesized ``mem_w_stream`` kernel (a real Vitis ``m_axi`` master, from
``examples/interleaver``) writes packets into an ``mm_queue_in`` window through AMD's crossbar, and the
kernel side of the queue -- an ``AxisSlave`` -- receives them.  A host BFM shares the crossbar (SI1)
and reads the queue's vacancy, so the response routing by ID is exercised with an HLS master on SI0.

The producer is the testbench: per packet it presents one ``MWCmd{addr=0, len=n+1}`` on ``s_cmd``
and ``[n | data x n]`` on ``s_in``.  That is all a kernel needs to do to reach another kernel's queue:
point ``MemWStream`` at the window and prepend the length.

The pysim twin is ``tests/hw/test_mm_queue.py::test_producer_reaches_consumer_queue_through_memwstream``.

Run: ``pytest tests/build/test_mm_queue_memw_xsi.py -m xsi`` (needs Vivado and a csynth of
``examples/interleaver``'s ``mem_w_stream``).
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from waveflow.build.axi_xbar import (
    AxiXbarConfig,
    AxiXbarRange,
    axi_port_decls,
    axi_signals,
    axi_wire_decls,
    generate_axi_xbar,
    render_xbar_instance,
)
from waveflow.build.mm_adaptor_gen import (
    QueueView,
    axis_port_decls,
    leaf_sources,
    mi_wire_signals,
    render_queue_slot,
)
from waveflow.build.trace_steps import rtl_staleness
from waveflow.build.xsi_workspace import XsiWorkspace
from waveflow.hw.mem_stream import MWCmd
from waveflow.toolchain.toolchain import find_vivado_path

REPO = Path(__file__).resolve().parents[2]
WORK = Path(__file__).resolve().parent / "_xsi_work"
IL = REPO / "examples" / "interleaver"
MEMW_RTL = IL / "mem_w_stream_proj" / "solution1" / "syn" / "verilog"

XBAR = AxiXbarConfig(name="xbar_memw_2x1", n_si=2, mi=[AxiXbarRange(0x0000_0000, 12)],
                     data_width=64, addr_width=32, id_width=1)
VIEW = QueueView("qin", "in", axis="k_in", depth=64)
PACKETS = [list(range(0x100, 0x108)), list(range(0x200, 0x220)), list(range(0x300, 0x303))]

#: mem_w_stream's m_axi signals that the crossbar SI carries, with the width the crossbar wants
#: (HLS emits an AXI3-style 2-bit LOCK and a 64-bit address; the crossbar is AXI4, 32-bit).
_HLS_TO_XBAR = {"AWLOCK": "[0:0]", "ARLOCK": "[0:0]", "AWADDR": "[31:0]", "ARADDR": "[31:0]"}


def render_top(top: str) -> str:
    dw, aw, idw = XBAR.data_width, XBAR.addr_width, XBAR.id_width
    ports = ["input wire ap_clk", "input wire ap_rst_n"]
    ports += axi_port_decls("s1_axi", axi_signals(dw, aw, idw), facing="slave")       # host BFM
    ports += [f"input  wire [63:0] s_cmd_TDATA", "input  wire s_cmd_TVALID", "output wire s_cmd_TREADY",
              f"input  wire [63:0] s_in_TDATA", "input  wire s_in_TVALID", "output wire s_in_TREADY"]
    ports += axis_port_decls("k_in", dw, kernel_reads=True)
    body = ["  " + d for d in axi_wire_decls("s0_axi", axi_signals(dw, aw, idw))]
    body += ["  " + d for d in axi_wire_decls("mi0_axi", mi_wire_signals(dw, aw, idw))]
    # The HLS master on SI0.  Its pointer is offset=off (no base register, no control slave): the
    # bus address is the command's word coordinate times the word size.
    conns = ["    .ap_clk(ap_clk)", "    .ap_rst_n(ap_rst_n)",
             "    .s_cmd_TDATA(s_cmd_TDATA)", "    .s_cmd_TVALID(s_cmd_TVALID)", "    .s_cmd_TREADY(s_cmd_TREADY)",
             "    .s_in_TDATA(s_in_TDATA)", "    .s_in_TVALID(s_in_TVALID)", "    .s_in_TREADY(s_in_TREADY)"]
    for name, _w, m2s in axi_signals(dw, aw, idw):
        net = f"s0_axi_{name}"
        if name in _HLS_TO_XBAR and m2s:
            body.append(f"  wire [{'63' if 'ADDR' in name else '1'}:0] hls_{name};")
            body.append(f"  assign {net} = hls_{name}{_HLS_TO_XBAR[name]};")
            conns.append(f"    .m_axi_gmem0_{name}(hls_{name})")
        else:
            conns.append(f"    .m_axi_gmem0_{name}({net})")
    conns += ["    .m_axi_gmem0_RUSER(1'b0)", "    .m_axi_gmem0_BUSER(1'b0)"]
    body.append("  mem_w_stream u_memw (\n" + ",\n".join(conns) + "\n  );")
    body.append(render_xbar_instance(XBAR, "u_xbar", ["s0_axi", "s1_axi"], ["mi0_axi"]))
    body.append(render_queue_slot(VIEW, "mi0_axi", dw, aw, idw))
    return (f"// {top}.v -- GENERATED by tests/build/test_mm_queue_memw_xsi.py.\n"
            f"`timescale 1ns/1ps\nmodule {top} (\n  " + ",\n  ".join(ports) + "\n);\n"
            + "\n".join(body) + "\nendmodule\n")


def _words_cpp(words) -> str:
    return "{" + ", ".join(f"0x{int(w):x}ull" for w in words) + "}"


def render_tb(dll: str) -> str:
    cmd = np.concatenate([np.asarray(MWCmd(addr=0, len=len(p) + 1).serialize(word_bw=64),
                                     dtype=np.uint64) for p in PACKETS])
    dat = [w for p in PACKETS for w in [len(p)] + p]
    flat = [w for p in PACKETS for w in p]
    bounds, acc = [], 0
    for p in PACKETS:
        acc += len(p)
        bounds.append(acc)
    return f'''// memw_q_tb.cpp -- Producer (TB) -> mem_w_stream -> crossbar -> mm_queue_in -> sink.
#include "xsi_bfm.h"
using namespace wfbfm;
int main() {{
    XsiSim sim("{dll}", "memw_q.wdb");
    AxisMaster cmd(sim.dut(), "s_cmd", {_words_cpp(cmd)});
    AxisMaster dat(sim.dut(), "s_in", {_words_cpp(dat)});
    AxisSlave sink(sim.dut(), "k_in");
    AxiMmMaster host(sim.dut(), "s1_axi", 8, 1);
    size_t v = host.read(0x0, 1, 400);          // vacancy, once everything has drained
    std::vector<XsiSimObj*> all = {{&cmd, &dat, &sink, &host}};
    auto drive = [&] {{ for (auto* p : all) p->drive(); }};
    sim.reset(drive);
    const std::vector<uint64_t> want = {_words_cpp(flat)};
    long cyc = 0;
    for (; cyc < 3000 && !(host.idle() && sink.count() >= want.size()); ++cyc) {{
        sim.clock_low();  for (auto* p : all) p->sample();
        sim.clock_high(); for (auto* p : all) p->update(); drive();
    }}
    int fail = 0;
    auto check = [&](const char* w, bool ok) {{ if (!ok) {{ std::printf("FAIL %s\\n", w); ++fail; }} }};
    check("sink words", sink.words() == want);
    check("TLAST bounds", sink.bounds() == std::vector<uint64_t>({_words_cpp(bounds).replace("ull", "")}));
    check("vacancy", host.op(v).rdata.size() == 1 && host.op(v).rdata[0] == {VIEW.depth});
    check("host OKAY", host.op(v).resp == 0);
    std::printf("SINK first=%ld p1=%ld p2=%ld p3=%ld\\n", sink.cycle_of_word(1),
                sink.cycle_of_word({bounds[0]}), sink.cycle_of_word({bounds[1]}),
                sink.cycle_of_word({bounds[2]}));
    std::printf(fail ? "FAILED test (%d)\\n" : "PASSED test\\n", fail);
    sim.close();
    return fail ? 1 : 0;
}}
'''


@pytest.fixture(scope="module")
def memw_run() -> str:
    if not find_vivado_path():
        pytest.skip("XSI gate prerequisite missing: Vivado (create_ip + xsim)")
    if not MEMW_RTL.is_dir():
        pytest.skip(f"XSI gate prerequisite missing: no csynth RTL at {MEMW_RTL}")
    stale = rtl_staleness(IL, "mem_w_stream")
    if stale is not None:
        pytest.skip(f"XSI gate prerequisite missing: {stale}")
    ip = generate_axi_xbar(XBAR, WORK / "ip")
    ws = XsiWorkspace(WORK / "memw_q", top="memw_q_top")
    hls = sorted(MEMW_RTL.glob("*.v"))
    ws.prepare(rtl_files=ip.sim_files + leaf_sources() + hls + ["memw_q_top.v"],
               include_dirs=ip.include_dirs, tb_name="memw_q_tb", tb_cpp=render_tb(ws.design_dll),
               extra_files={"memw_q_top.v": render_top("memw_q_top")})
    return ws.run()


@pytest.mark.xsi
def test_memw_reaches_queue_functional(memw_run: str):
    assert "PASSED test" in memw_run, memw_run[-3000:]


def _parse(out: str, tag: str) -> dict[str, int]:
    line = next(ln for ln in out.splitlines() if ln.startswith(tag + " "))
    return {k: int(v) for k, v in (kv.split("=") for kv in line.split()[1:])}


@pytest.mark.xsi
def test_memw_reaches_queue_cycles(memw_run: str):
    sink = _parse(memw_run, "SINK")
    print(sink)
    assert sink == EXPECTED_SINK, f"sink timing moved: {sink}"


#: Cycle the sink took the first word, and the last word of each packet (8, 32 and 3 words).
#: Recorded 2026-10-02 against mem_w_stream RTL re-synthesized (and source-stamped) that day.
#:
#: The pysim twin, with the crossbar at latency_init = 4, delivers the three packets at 28 / 67 / 80
#: -- increasingly early, because each MemWStream command costs ~30-40 cycles more in RTL than in its
#: UNCALIBRATED pysim model (RTL: 78 cycles from packet 1 to packet 2, 32 from 2 to 3; pysim: 39 and
#: 13).  The adaptor is not the gap: test_mm_queue.py::test_pysim_timing_tracks_the_rtl_gate holds it
#: to within 2 cycles of RTL.  Closing this one is MemWStream's calibration (its calib_dir), not this
#: plan's.
EXPECTED_SINK: dict[str, int] = {"first": 32, "p1": 39, "p2": 117, "p3": 149}
