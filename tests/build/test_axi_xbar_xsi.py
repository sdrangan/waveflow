"""Stage 0 of ``plans/mm_slave_adaptor.md`` — AMD's ``axi_crossbar`` IP, generated and run under XSI.

The witness: two :class:`wfbfm::AxiMmMaster` BFMs (a host each) drive a generated 2x2 crossbar whose
two MI slots are served by the existing memory BFMs.  It answers the plan's open question — does the
generated IP simulate under XSI without a Vivado project? — and measures what a transaction through
the crossbar costs, which every later stage's cycle count includes.

Run: ``pytest tests/build/test_axi_xbar_xsi.py -m xsi`` (needs Vivado: ``create_ip`` + xsim + g++).

The memory BFMs serve one transaction at a time and do not drive ``BID``/``RID``.  The crossbar
routes a response back to its SI by that ID, so the witness top latches ``AWID``/``ARID`` per MI and
echoes it — correct exactly because a memory BFM holds ``AWREADY`` low until its ``B`` is taken, so
there is never more than one write (or read) in flight per MI.  It also masks the address to the MI's
window, so each memory sees a local offset, as the adaptor's front end will.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from waveflow.build.axi_xbar import (
    AxiXbarConfig,
    AxiXbarRange,
    axi_port_decls,
    axi_signals,
    axi_wire_decls,
    generate_axi_xbar,
    render_xbar_instance,
)
from waveflow.build.xsi_workspace import XsiWorkspace
from waveflow.toolchain.toolchain import find_vivado_path

WORK = Path(__file__).resolve().parent / "_xsi_work"

XBAR = AxiXbarConfig(
    name="xbar_witness_2x2", n_si=2,
    mi=[AxiXbarRange(0x0000_0000, 16), AxiXbarRange(0x0001_0000, 16)],
    data_width=64, addr_width=32, id_width=1,
)

#: What the memory BFMs read/drive (AxiMmReadSlave / AxiMmWriteSlave).  Everything else on the MI
#: side is terminated inside the witness top.
_BFM_SLAVE_SIGS = ("AWADDR", "AWLEN", "AWVALID", "AWREADY", "WDATA", "WSTRB", "WLAST", "WVALID",
                   "WREADY", "BVALID", "BREADY", "ARADDR", "ARLEN", "ARVALID", "ARREADY", "RDATA",
                   "RLAST", "RVALID", "RREADY")


def render_witness_top(cfg: AxiXbarConfig, top: str) -> str:
    si = [f"s{k}_axi" for k in range(cfg.n_si)]
    mi_int = [f"mx{k}_axi" for k in range(len(cfg.mi))]
    mi_ext = [f"m{k}_axi" for k in range(len(cfg.mi))]
    sig_si = axi_signals(cfg.data_width, cfg.addr_width, cfg.id_width)
    sig_mi = axi_signals(cfg.data_width, cfg.addr_width, cfg.id_width, region=True)
    sig_bfm = [s for s in sig_mi if s[0] in _BFM_SLAVE_SIGS]

    ports = ["input wire ap_clk", "input wire ap_rst_n"]
    for p in si:
        ports += axi_port_decls(p, sig_si, facing="slave")
    for p in mi_ext:
        ports += axi_port_decls(p, sig_bfm, facing="master")
    body = []
    for p in mi_int:
        body += axi_wire_decls(p, sig_mi)
    body.append(render_xbar_instance(cfg, "u_xbar", si, mi_int))
    for k, (pi, pe) in enumerate(zip(mi_int, mi_ext)):
        mask = cfg.mi[k].size - 1
        for name, _w, m2s in sig_bfm:
            if name in ("AWADDR", "ARADDR"):
                body.append(f"assign {pe}_{name} = {pi}_{name} & {cfg.addr_width}'h{mask:x};")
            elif m2s:
                body.append(f"assign {pe}_{name} = {pi}_{name};")
            else:
                body.append(f"assign {pi}_{name} = {pe}_{name};")
        idw = cfg.id_width
        body += [
            f"reg [{idw - 1}:0] {pi}_bid_q, {pi}_rid_q;",
            "always @(posedge ap_clk) begin",
            f"  if (!ap_rst_n) begin {pi}_bid_q <= 0; {pi}_rid_q <= 0; end",
            "  else begin",
            f"    if ({pi}_AWVALID && {pi}_AWREADY) {pi}_bid_q <= {pi}_AWID;",
            f"    if ({pi}_ARVALID && {pi}_ARREADY) {pi}_rid_q <= {pi}_ARID;",
            "  end",
            "end",
            f"assign {pi}_BID = {pi}_bid_q;",
            f"assign {pi}_RID = {pi}_rid_q;",
            f"assign {pi}_BRESP = 2'b00;",
            f"assign {pi}_RRESP = 2'b00;",
        ]
    return (f"// {top}.v -- GENERATED by tests/build/test_axi_xbar_xsi.py (Stage 0 witness).\n"
            f"`timescale 1ns/1ps\nmodule {top} (\n  " + ",\n  ".join(ports) + "\n);\n"
            + "\n".join(body) + "\nendmodule\n")


TB = r'''// xbar_witness_tb.cpp -- Stage 0 witness: two AXI masters through the generated crossbar.
#include "xsi_bfm.h"
using namespace wfbfm;

static std::vector<uint64_t> ramp(uint64_t base, int n) {
    std::vector<uint64_t> v; for (int i = 0; i < n; ++i) v.push_back(base + (uint64_t)i * 0x0101); return v;
}

int main() {
    XsiSim sim("__DLL__", "xbar_witness.wdb");
    FlatMemory mem0(8192, 8), mem1(8192, 8);
    AxiMmMaster h0(sim.dut(), "s0_axi", 8, 0), h1(sim.dut(), "s1_axi", 8, 1);
    AxiMmReadSlave r0(sim.dut(), "m0_axi", mem0), r1(sim.dut(), "m1_axi", mem1);
    AxiMmWriteSlave w0(sim.dut(), "m0_axi", mem0), w1(sim.dut(), "m1_axi", mem1);
    std::vector<XsiSimObj*> all = {&mem0, &mem1, &h0, &h1, &r0, &r1, &w0, &w1};
    auto drive = [&] { for (auto* p : all) p->drive(); };

    // Phase 1, uncontended: each host writes then reads back its own MI.  Lengths 1 and 16 isolate
    // the per-transaction cost from the per-beat cost.
    size_t a1 = h0.write(0x0000'0100, ramp(0xA000, 1));
    size_t a2 = h0.write(0x0000'0200, ramp(0xA100, 16));
    size_t a3 = h0.read (0x0000'0200, 16);
    size_t b1 = h1.write(0x0001'0040, ramp(0xB000, 8));
    size_t b2 = h1.read (0x0001'0040, 8);
    // Phase 2, contended: both hosts burst 32 words into MI0 starting the same cycle.
    size_t a4 = h0.write(0x0000'1000, ramp(0xC000, 32), 400);
    size_t b3 = h1.write(0x0000'2000, ramp(0xD000, 32), 400);
    size_t a5 = h0.read (0x0000'1000, 32);
    size_t b4 = h1.read (0x0000'2000, 32);

    for (auto* p : all) p->pre_sim();
    sim.reset(drive);
    long cyc = 0;
    for (; cyc < 4000 && !(h0.idle() && h1.idle()); ++cyc) {
        sim.clock_low();  for (auto* p : all) p->sample();
        sim.clock_high(); for (auto* p : all) p->update(); drive();
    }
    for (auto* p : all) p->post_sim();

    int fail = 0;
    auto check = [&](const char* what, bool ok) { if (!ok) { std::printf("FAIL %s\n", what); ++fail; } };
    check("hosts idle", h0.idle() && h1.idle());
    check("mem0 single word", mem0[0x100 / 8] == 0xA000);
    for (int i = 0; i < 16; ++i) check("mem0 burst", mem0[0x200 / 8 + i] == 0xA100 + (uint64_t)i * 0x0101);
    for (int i = 0; i < 8; ++i)  check("mem1 burst", mem1[0x40 / 8 + i] == 0xB000 + (uint64_t)i * 0x0101);
    check("a3 readback", h0.op(a3).rdata == ramp(0xA100, 16));
    check("b2 readback", h1.op(b2).rdata == ramp(0xB000, 8));
    check("a5 readback", h0.op(a5).rdata == ramp(0xC000, 32));
    check("b4 readback", h1.op(b4).rdata == ramp(0xD000, 32));
    for (size_t i = 0; i < h0.nops(); ++i) check("h0 resp OKAY", h0.op(i).resp == 0);
    for (size_t i = 0; i < h1.nops(); ++i) check("h1 resp OKAY", h1.op(i).resp == 0);

    auto lat = [](const AxiMmMaster::Op& o) { return o.t_end - o.t_start + 1; };
    std::printf("LAT write1=%ld write16=%ld read16=%ld write8=%ld read8=%ld\n",
                lat(h0.op(a1)), lat(h0.op(a2)), lat(h0.op(a3)), lat(h1.op(b1)), lat(h1.op(b2)));
    std::printf("CONTEND h0_start=%ld h0_end=%ld h1_start=%ld h1_end=%ld\n",
                h0.op(a4).t_start, h0.op(a4).t_end, h1.op(b3).t_start, h1.op(b3).t_end);
    for (size_t i = 0; i < h0.nops(); ++i)
        std::printf("OP h0 %zu %c start=%ld end=%ld\n", i, h0.op(i).write ? 'W' : 'R', h0.op(i).t_start, h0.op(i).t_end);
    for (size_t i = 0; i < h1.nops(); ++i)
        std::printf("OP h1 %zu %c start=%ld end=%ld\n", i, h1.op(i).write ? 'W' : 'R', h1.op(i).t_start, h1.op(i).t_end);
    std::printf("cycles=%ld\n", cyc);
    std::printf(fail ? "FAILED test (%d)\n" : "PASSED test\n", fail);
    sim.close();
    return fail ? 1 : 0;
}
'''


def _require_vivado() -> None:
    if not find_vivado_path():
        pytest.skip("XSI gate prerequisite missing: Vivado (create_ip + xsim)")


def _parse(out: str, tag: str) -> dict[str, int]:
    line = next(ln for ln in out.splitlines() if ln.startswith(tag + " "))
    return {k: int(v) for k, v in (kv.split("=") for kv in line.split()[1:])}


@pytest.mark.xsi
def test_axi_xbar_witness_xsi():
    _require_vivado()
    ip = generate_axi_xbar(XBAR, WORK / "ip")
    ws = XsiWorkspace(WORK / "xbar_witness", top="xbar_witness")
    top_v = render_witness_top(XBAR, "xbar_witness")
    ws.prepare(rtl_files=ip.sim_files + ["xbar_witness.v"], include_dirs=ip.include_dirs,
               tb_name="xbar_witness_tb", tb_cpp=TB.replace("__DLL__", ws.design_dll),
               extra_files={"xbar_witness.v": top_v})
    out = ws.run()
    assert "PASSED test" in out, out[-3000:]
    lat = _parse(out, "LAT")
    con = _parse(out, "CONTEND")
    print(lat, con)
    # Exact numbers, recorded from the first run (see plans/mm_slave_adaptor.md, Stage 0).
    assert lat == EXPECTED_LAT, f"crossbar latency moved: {lat} (want {EXPECTED_LAT})"
    assert con == EXPECTED_CONTEND, f"contended schedule moved: {con} (want {EXPECTED_CONTEND})"


#: Cycles per transaction, address phase presented -> B (write) or RLAST (read), inclusive.
#: Recorded 2026-10-02, Vivado 2025.1, xczu48dr.  Uncontended, a burst costs about 5 cycles plus one
#: per beat (write16 = 21, read16 = 20; write1 = 7).  ``write8`` is NOT uncontended: host 1 issued it
#: in the same cycle as host 0's ``write1``, and although the two went to DIFFERENT MIs it finished
#: about 4 cycles later than the slope predicts (17, not ~13).  Our reading is that the two address
#: phases contend for the crossbar's shared address arbiter (the SAMD crossbar has one per channel
#: direction, PG059); we have not yet confirmed this in the waveform.
EXPECTED_LAT: dict[str, int] = {"write1": 7, "write16": 21, "read16": 20, "write8": 17, "read8": 12}
#: Both hosts burst 32 words into the SAME MI in the same cycle.  One wins (37 = 32 + 5) and the
#: other's whole burst waits behind it (71): AXI4 write data cannot interleave, so a crossbar
#: serializes bursts to one slave, and a slow slave stalls every master writing to it.
EXPECTED_CONTEND: dict[str, int] = {"h0_start": 401, "h0_end": 471, "h1_start": 401, "h1_end": 437}
