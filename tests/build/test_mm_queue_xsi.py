"""Stage 1 of ``plans/mm_slave_adaptor.md`` — the queue windows, through the real crossbar, under XSI.

One host (:class:`wfbfm::AxiMmMaster`) reaches two queue views through AMD's ``axi_crossbar``:

* MI0 = ``mm_queue_in`` (4 KB at 0x0000): bus writes push an AXIS stream, taken by an ``AxisSlave``
  sink that is held OFF until cycle ``SINK_FROM`` so the FIFO fills and the host's burst stalls.
* MI1 = ``mm_queue_out`` (4 KB at 0x1000): an ``AxisMaster`` pushes words in; bus reads pop them
  (data half 0x1000..0x17FF) or read the occupancy (status half 0x1800..).

What it checks: in-band framing (a packet split across two bursts still gets TLAST on its last word;
the header is never pushed), the vacancy and occupancy reads, back-pressure (a write into a full FIFO
stalls and then completes, losing nothing), and that reading an empty queue returns SLVERR rather than
hanging the bus.  The cycle numbers are exact.

Run: ``pytest tests/build/test_mm_queue_xsi.py -m xsi`` (needs Vivado).
"""
from __future__ import annotations

from pathlib import Path

import pytest

from waveflow.build.axi_xbar import (
    AxiXbarConfig,
    AxiXbarRange,
    axi_port_decls,
    axi_signals,
    axi_wire_decls,
    generate_axi_xbar,
    render_xbar_instance,
)
from waveflow.build.mm_adaptor_gen import (
    QueueView,
    axis_port_decls,
    leaf_sources,
    mi_wire_signals,
    render_queue_slot,
)
from waveflow.build.xsi_workspace import XsiWorkspace
from waveflow.toolchain.toolchain import find_vivado_path

WORK = Path(__file__).resolve().parent / "_xsi_work"
DEPTH = 64
SINK_FROM = 600

XBAR = AxiXbarConfig(
    name="xbar_mmq_1x2", n_si=1,
    mi=[AxiXbarRange(0x0000_0000, 12), AxiXbarRange(0x0000_1000, 12)],
    data_width=64, addr_width=32, id_width=1,
)
VIEWS = [QueueView("qin", "in", axis="k_in", depth=DEPTH),
         QueueView("qout", "out", axis="k_out", depth=DEPTH)]


def render_top(top: str) -> str:
    dw, aw, idw = XBAR.data_width, XBAR.addr_width, XBAR.id_width
    ports = ["input wire ap_clk", "input wire ap_rst_n"]
    ports += axi_port_decls("s0_axi", axi_signals(dw, aw, idw), facing="slave")
    ports += axis_port_decls("k_in", dw, kernel_reads=True)
    ports += axis_port_decls("k_out", dw, kernel_reads=False)
    body = []
    mi = [f"mi{k}_axi" for k in range(len(VIEWS))]
    for p in mi:
        body += ["  " + d for d in axi_wire_decls(p, mi_wire_signals(dw, aw, idw))]
    body.append(render_xbar_instance(XBAR, "u_xbar", ["s0_axi"], mi))
    for view, p in zip(VIEWS, mi):
        body.append(render_queue_slot(view, p, dw, aw, idw))
    return (f"// {top}.v -- GENERATED by tests/build/test_mm_queue_xsi.py (Stage 1 gate).\n"
            f"`timescale 1ns/1ps\nmodule {top} (\n  " + ",\n  ".join(ports) + "\n);\n"
            + "\n".join(body) + "endmodule\n")


TB = r'''// mmq_tb.cpp -- Stage 1 gate: queue_in / queue_out behind the crossbar.
#include "xsi_bfm.h"
using namespace wfbfm;

static std::vector<uint64_t> ramp(uint64_t base, int n) {
    std::vector<uint64_t> v; for (int i = 0; i < n; ++i) v.push_back(base + (uint64_t)i); return v;
}
static std::vector<uint64_t> cat(std::vector<uint64_t> a, const std::vector<uint64_t>& b) {
    a.insert(a.end(), b.begin(), b.end()); return a;
}

int main() {
    XsiSim sim("__DLL__", "mmq.wdb");
    const uint64_t QIN = 0x0000, QOUT = 0x1000, QOUT_STATUS = 0x1800;
    std::vector<uint64_t> d = ramp(0x1000, 16), e = ramp(0x2000, 40), f = ramp(0x3000, 100);
    std::vector<uint64_t> g = ramp(0x9000, 48);

    AxiMmMaster host(sim.dut(), "s0_axi", 8, 0);
    AxisSlave  sink(sim.dut(), "k_in");
    AxisMaster src(sim.dut(), "k_out", g);
    sink.ready_from = __SINK_FROM__;
    std::vector<XsiSimObj*> all = {&host, &sink, &src};
    auto drive = [&] { for (auto* p : all) p->drive(); };

    size_t v0 = host.read(QIN, 1);                                    // vacancy, empty queue
    size_t w1 = host.write(QIN, cat({16}, d));                        // one packet, one burst
    size_t w2 = host.write(QIN, cat({40}, ramp(0x2000, 10)));         // a packet split ...
    size_t w3 = host.write(QIN, std::vector<uint64_t>(e.begin() + 10, e.end()));  // ... over two bursts
    size_t v1 = host.read(QIN, 1);                                    // vacancy, 56 words queued
    size_t w4 = host.write(QIN, cat({100}, f));                       // fills the FIFO: stalls
    size_t o0 = host.read(QOUT_STATUS, 1);                            // occupancy
    size_t r1 = host.read(QOUT, 32);
    size_t r2 = host.read(QOUT, 16);
    size_t r3 = host.read(QOUT, 1);                                   // empty: SLVERR, no hang
    size_t o1 = host.read(QOUT_STATUS, 1);
    // Faults: a partial-strobe burst and a wrong-size burst are refused (SLVERR) and push NOTHING --
    // not even into the framing state, so the good packet after them still starts with a header.
    size_t x1 = host.write(QIN, {2, 0xBAD0, 0xBAD1});
    host.op_mut(x1).wstrb = 0x0F;
    size_t x2 = host.write(QIN, {2, 0xBAD2, 0xBAD3});
    host.op_mut(x2).size = 2;
    std::vector<uint64_t> h = {0x7700, 0x7701};
    size_t w5 = host.write(QIN, cat({2}, h));

    sim.reset(drive);
    long cyc = 0;
    const size_t want_words = d.size() + e.size() + f.size() + h.size();
    for (; cyc < 4000 && !(host.idle() && sink.count() >= want_words); ++cyc) {
        sim.clock_low();  for (auto* p : all) p->sample();
        sim.clock_high(); for (auto* p : all) p->update(); drive();
    }

    int fail = 0;
    auto check = [&](const char* what, bool ok) { if (!ok) { std::printf("FAIL %s\n", what); ++fail; } };
    check("host idle", host.idle());
    check("sink words", sink.words() == cat(cat(cat(d, e), f), h));
    check("sink TLAST bounds", sink.bounds() == std::vector<uint64_t>({16, 56, 156, 158}));
    check("bad strobe SLVERR", host.op(x1).resp == 2);
    check("bad size SLVERR", host.op(x2).resp == 2);
    check("vacancy empty", host.op(v0).rdata.size() == 1 && host.op(v0).rdata[0] == __DEPTH__);
    check("vacancy after 56", host.op(v1).rdata.size() == 1 && host.op(v1).rdata[0] == __DEPTH__ - 56);
    check("occupancy 48", host.op(o0).rdata.size() == 1 && host.op(o0).rdata[0] == 48);
    check("pop 32", host.op(r1).rdata == std::vector<uint64_t>(g.begin(), g.begin() + 32));
    check("pop 16", host.op(r2).rdata == std::vector<uint64_t>(g.begin() + 32, g.end()));
    check("empty pop SLVERR", host.op(r3).resp == 2 && host.op(r3).rdata == std::vector<uint64_t>({0}));
    check("occupancy 0", host.op(o1).rdata.size() == 1 && host.op(o1).rdata[0] == 0);
    for (size_t i : {w1, w2, w3, w4, w5, v0, v1, o0, r1, r2, o1}) check("resp OKAY", host.op(i).resp == 0);

    const char* names[] = {"v0", "w1", "w2", "w3", "v1", "w4", "o0", "r1", "r2", "r3", "o1", "x1", "x2",
                           "w5"};
    std::printf("LAT");
    for (size_t i = 0; i < host.nops(); ++i)
        std::printf(" %s=%ld", names[i], host.op(i).t_end - host.op(i).t_start + 1);
    std::printf("\nEND");
    for (size_t i = 0; i < host.nops(); ++i) std::printf(" %s=%ld", names[i], host.op(i).t_end);
    std::printf("\nSINK first=%ld last=%ld\n", sink.cycle_of_word(1), sink.cycle_of_word(want_words));
    std::printf(fail ? "FAILED test (%d)\n" : "PASSED test\n", fail);
    sim.close();
    return fail ? 1 : 0;
}
'''


def _parse(out: str, tag: str) -> dict[str, int]:
    line = next(ln for ln in out.splitlines() if ln.startswith(tag + " "))
    return {k: int(v) for k, v in (kv.split("=") for kv in line.split()[1:])}


@pytest.fixture(scope="module")
def mmq_run() -> str:
    if not find_vivado_path():
        pytest.skip("XSI gate prerequisite missing: Vivado (create_ip + xsim)")
    ip = generate_axi_xbar(XBAR, WORK / "ip")
    ws = XsiWorkspace(WORK / "mmq", top="mmq_top")
    tb = (TB.replace("__DLL__", ws.design_dll).replace("__SINK_FROM__", str(SINK_FROM))
          .replace("__DEPTH__", str(DEPTH)))
    ws.prepare(rtl_files=ip.sim_files + leaf_sources() + ["mmq_top.v"],
               include_dirs=ip.include_dirs, tb_name="mmq_tb", tb_cpp=tb,
               extra_files={"mmq_top.v": render_top("mmq_top")})
    return ws.run()


@pytest.mark.xsi
def test_mm_queue_functional(mmq_run: str):
    assert "PASSED test" in mmq_run, mmq_run[-3000:]


@pytest.mark.xsi
def test_mm_queue_cycles(mmq_run: str):
    lat, end, sink = _parse(mmq_run, "LAT"), _parse(mmq_run, "END"), _parse(mmq_run, "SINK")
    print(lat, end, sink)
    assert lat == EXPECTED_LAT, f"latency moved: {lat}"
    assert sink == EXPECTED_SINK, f"sink timing moved: {sink}"


#: Cycles per host transaction (address phase presented -> B or RLAST, inclusive), recorded
#: 2026-10-02.  Both directions sustain ONE BEAT PER CYCLE after a fixed 4-5 cycles through the
#: crossbar and the front: w1 = 17 beats + 5, w3 = 30 + 4, r1 = 32 + 4.  w4 is the back-pressure case:
#: 56 words are already queued, so the header + 8 words fill the 64-slot FIFO and WREADY drops until
#: the sink opens at cycle 601; the remaining 92 words then drain at the sink's rate and the burst
#: ends at 695 = 601 + 92 + 2.  r3 pops an EMPTY queue and returns SLVERR in 5 cycles instead of
#: waiting.  x1 (partial WSTRB) and x2 (AWSIZE = 4 bytes on a 64-bit bus) are refused with SLVERR at
#: full speed -- their beats are consumed and dropped, never pushed.
EXPECTED_LAT: dict[str, int] = {"v0": 6, "w1": 22, "w2": 15, "w3": 34, "v1": 5, "w4": 612, "o0": 6,
                                "r1": 36, "r2": 20, "r3": 5, "o1": 5, "x1": 7, "x2": 7, "w5": 7}
#: The sink is held off until SINK_FROM; it then takes all 156 queued words back to back (601..756) --
#: nothing was lost or reordered by the stall -- and the final 2-word packet (w5) lands at 787.
EXPECTED_SINK: dict[str, int] = {"first": 601, "last": 787}
